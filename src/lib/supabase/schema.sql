-- ------------------------------------------------------------------------------------------------
-- 5. PEMICU (TRIGGERS)
-- ------------------------------------------------------------------------------------------------
-- Trigger yang berjalan setiap kali user baru dibuat di `auth.users`.
DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
AFTER INSERT ON auth.users
FOR EACH ROW
EXECUTE PROCEDURE public.handle_new_user ();

-- Trigger yang berjalan setiap ada pengajuan cuti baru
DROP TRIGGER IF EXISTS create_admin_notification_for_new_leave ON public.leave_requests;
CREATE TRIGGER create_admin_notification_for_new_leave
AFTER INSERT ON public.leave_requests
FOR EACH ROW
EXECUTE FUNCTION public.notify_admin_on_new_leave();

