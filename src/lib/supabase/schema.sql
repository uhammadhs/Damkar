-- 5. FUNGSI-FUNGSI HELPER (RPC)
-- Kumpulan fungsi yang bisa dipanggil dari aplikasi untuk melakukan operasi kompleks.
-- -----------------------------------------------------------------------------------------------

-- Function untuk meng-handle reset saldo cuti di awal tahun.
CREATE OR REPLACE FUNCTION public.handle_new_year_leave_balances()
RETURNS void AS $$
DECLARE
  user_profile record;
  current_year integer;
BEGIN
  current_year := EXTRACT(YEAR FROM NOW());

  -- Loop melalui semua profil pengguna dengan role 'anggota'
  FOR user_profile IN SELECT id FROM public.profiles WHERE role = 'anggota' LOOP
    -- Cek apakah sudah ada entri saldo untuk tahun ini
    IF NOT EXISTS (
      SELECT 1
      FROM public.leave_balances
      WHERE user_id = user_profile.id AND year = current_year
    ) THEN
      -- Jika belum ada, buat entri baru dengan saldo 12 hari
      INSERT INTO public.leave_balances (user_id, year, total_days, used_days)
      VALUES (user_profile.id, current_year, 12, 0);
    END IF;
  END LOOP;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;


-- Function untuk login menggunakan ID PJLP, bukan email.
CREATE OR REPLACE FUNCTION public.login_with_id_pjlp(p_id_pjlp TEXT, p_password TEXT)
RETURNS json AS $$
DECLARE
  user_email TEXT;
  user_id UUID;
  user_role TEXT;
  session_data JSON;
BEGIN
  -- 1. Cari email & id berdasarkan id_pjlp
  SELECT email, id, role INTO user_email, user_id, user_role
  FROM public.profiles
  WHERE id_pjlp = p_id_pjlp;

  -- 2. Jika tidak ditemukan, kembalikan error
  IF user_email IS NULL THEN
    RETURN json_build_object('error', 'ID PJLP tidak ditemukan.');
  END IF;
  
  -- 3. Coba login menggunakan email yang ditemukan.
  -- Ini memerlukan role `supabase_auth_admin` yang harus diberikan ke `postgres` user.
  -- GRANT supabase_auth_admin TO postgres;
  SELECT sign_in_with_password(user_email, p_password) INTO session_data;

  -- 4. Cek hasil dari `sign_in_with_password`
  IF session_data ->> 'access_token' IS NULL THEN
     RETURN json_build_object('error', 'Password yang Anda masukkan salah.');
  END IF;
  
  -- 5. Jika berhasil, kembalikan role pengguna.
  RETURN json_build_object('success', true, 'role', user_role);

EXCEPTION WHEN others THEN
    -- Menangkap exception lain, misalnya jika fungsi `sign_in` tidak ada atau error lain.
    RAISE WARNING 'Login RPC Error: %', SQLERRM;
    RETURN json_build_object('error', 'Terjadi kesalahan internal saat login.');
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;


