-- 6. Buat Fungsi-Fungsi Helper
-- Fungsi untuk mendapatkan peran pengguna saat ini
create or replace function public.get_user_role()
returns text
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() is null then
    return 'anon';
  else
    return (select role from public.profiles where id = auth.uid());
  end if;
end;
$$;

-- Fungsi untuk mendapatkan semua ID admin
create or replace function public.get_admin_ids()
returns uuid[]
language plpgsql
security definer
set search_path = public
as $$
begin
    return array(select id from public.profiles where role = 'admin');
end;
$$;

-- Fungsi yang akan dipanggil oleh trigger saat ada pengajuan cuti baru
create or replace function public.create_admin_notification_for_new_leave()
returns trigger
language plpgsql
as $$
declare
    admin_id uuid;
    applicant_name text;
begin
    -- Get the applicant's name
    select name into applicant_name from public.profiles where id = new.user_id;

    -- Loop through all admin IDs and create a notification for each
    foreach admin_id in array public.get_admin_ids()
    loop
        insert into public.notifications(user_id, message, leave_request_id)
        values (admin_id, 'Pengajuan cuti baru dari ' || applicant_name || ' sedang menunggu persetujuan.', new.id);
    end loop;
    return new;
end;
$$;

-- Fungsi untuk membuat profil pengguna & saldo cuti awal saat user baru mendaftar
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  current_year int;
begin
  -- Buat profil
  insert into public.profiles (id, name, id_pjlp, phone, email)
  values (
    new.id,
    new.raw_user_meta_data->>'name',
    new.raw_user_meta_data->>'id_pjlp',
    new.raw_user_meta_data->>'phone',
    new.email
  );

  -- Buat saldo cuti awal untuk tahun berjalan
  current_year := extract(year from now());
  insert into public.leave_balances(user_id, year, total_days, used_days)
  values(new.id, current_year, 12, 0);
  
  return new;
end;
$$;

-- Fungsi untuk reset cuti tahunan
create or replace function public.handle_new_year_leave_balances()
returns void
language plpgsql
as $$
declare
    user_record record;
    current_year integer;
begin
    current_year := extract(year from now());

    for user_record in select id from public.profiles loop
        -- Cek apakah sudah ada entri untuk tahun ini
        if not exists (select 1 from public.leave_balances where user_id = user_record.id and year = current_year) then
            -- Jika tidak ada, buat entri baru
            insert into public.leave_balances(user_id, year, total_days, used_days)
            values (user_record.id, current_year, 12, 0);
        end if;
    end loop;
end;
$$;

-- 7. Kebijakan Keamanan (RLS)
-- Kebijakan untuk PROFILES
alter table "public"."profiles" enable row level security;
create policy "Public profiles are viewable by everyone." on public.profiles for select using (true);
create policy "Users can insert their own profile." on public.profiles for insert with check (auth.uid() = id);
create policy "Users can update own profile." on public.profiles for update using (auth.uid() = id);
create policy "Admins can manage all profiles." on public.profiles for all using (get_user_role() = 'admin');

-- Kebijakan untuk LEAVE_REQUESTS
alter table "public"."leave_requests" enable row level security;
create policy "Users can view their own leave requests." on public.leave_requests for select using (auth.uid() = user_id);
create policy "Users can create their own leave requests." on public.leave_requests for insert with check (auth.uid() = user_id);
create policy "Admins can view all leave requests." on public.leave_requests for select using (get_user_role() = 'admin');
create policy "Admins can update leave requests." on public.leave_requests for update using (get_user_role() = 'admin');

-- Kebijakan untuk LEAVE_BALANCES
alter table "public"."leave_balances" enable row level security;
create policy "Users can view their own leave balances." on public.leave_balances for select using (auth.uid() = user_id);
create policy "Admins can view all leave balances." on public.leave_balances for select using (get_user_role() = 'admin');
-- Hanya trigger/server yang boleh mengubah (melalui service_role)
create policy "Leave balances are managed by the system." on public.leave_balances for update using (false);

-- Kebijakan untuk NOTIFICATIONS
alter table "public"."notifications" enable row level security;
create policy "Users can view their own notifications." on public.notifications for select using (auth.uid() = user_id);
create policy "Users can update their own notifications." on public.notifications for update using (auth.uid() = user_id);
-- Hanya trigger/server yang boleh memasukkan notifikasi

-- 8. Triggers
-- Trigger untuk membuat profil saat user baru daftar
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

-- Trigger untuk membuat notifikasi admin saat ada pengajuan baru
create trigger on_leave_request_created
  after insert on public.leave_requests
  for each row execute procedure public.create_admin_notification_for_new_leave();


