-- 4. Create Triggers
-- ----------------------------
-- Trigger for handle_new_user
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

-- Trigger for on_new_user_create_leave_balance
drop trigger if exists on_profile_created on public.profiles;
create trigger on_profile_created
  after insert on public.profiles
  for each row execute procedure public.on_new_user_create_leave_balance();

-- Trigger for create_admin_notification_for_new_leave
drop trigger if exists on_new_leave_request on public.leave_requests;
create trigger on_new_leave_request
  after insert on public.leave_requests
  for each row execute procedure public.create_admin_notification_for_new_leave();

-- ----------------------------
-- 5. Set up Policies
-- ----------------------------

-- Policies for profiles table
drop policy if exists "Public profiles are viewable by everyone." on profiles;
create policy "Public profiles are viewable by everyone."
  on profiles for select
  using ( true );

drop policy if exists "Users can insert their own profile." on profiles;
create policy "Users can insert their own profile."
  on profiles for insert
  with check ( auth.uid() = id );

drop policy if exists "Users can update their own profile." on profiles;
create policy "Users can update their own profile."
  on profiles for update
  using ( auth.uid() = id );

drop policy if exists "Admins can manage all profiles." on profiles;
create policy "Admins can manage all profiles."
  on profiles for all
  using ( public.get_user_role() = 'admin' )
  with check ( public.get_user_role() = 'admin' );


-- Policies for leave_requests table
drop policy if exists "Users can view their own leave requests." on leave_requests;
create policy "Users can view their own leave requests."
  on leave_requests for select
  using ( auth.uid() = user_id );

drop policy if exists "Users can create leave requests for themselves." on leave_requests;
create policy "Users can create leave requests for themselves."
  on leave_requests for insert
  with check ( auth.uid() = user_id );

drop policy if exists "Admins can manage all leave requests." on leave_requests;
create policy "Admins can manage all leave requests."
  on leave_requests for all
  using ( public.get_user_role() = 'admin' );


-- Policies for leave_balances table
drop policy if exists "Users can view their own leave balances." on leave_balances;
create policy "Users can view their own leave balances."
  on leave_balances for select
  using ( auth.uid() = user_id );

drop policy if exists "Admins can manage all leave balances." on leave_balances;
create policy "Admins can manage all leave balances."
  on leave_balances for all
  using ( public.get_user_role() = 'admin' );


-- Policies for notifications table
drop policy if exists "Users can view their own notifications." on notifications;
create policy "Users can view their own notifications."
  on notifications for select
  using ( auth.uid() = user_id );
  
drop policy if exists "Users can update their own notifications." on notifications;
create policy "Users can update their own notifications."
  on notifications for update
  using ( auth.uid() = user_id );

