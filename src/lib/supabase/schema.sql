-- Tabel untuk menyimpan profil pengguna, terhubung ke tabel auth.users bawaan Supabase.
CREATE TABLE public.profiles (
    id uuid NOT NULL PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    name text,
    id_pjlp text UNIQUE,
    phone text,
    email text UNIQUE,
    role text DEFAULT 'anggota',
    avatar_url text,
    updated_at timestamp with time zone
);
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
COMMENT ON TABLE public.profiles IS 'Stores public profile information for each user.';

-- Tabel untuk menyimpan histori pengajuan cuti.
CREATE TABLE public.leave_requests (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    title text NOT NULL,
    reason text,
    start_date date NOT NULL,
    end_date date NOT NULL,
    duration integer NOT NULL,
    status text NOT NULL DEFAULT 'Menunggu',
    attachment_url text,
    is_read_by_user boolean NOT NULL DEFAULT false,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    updated_at timestamp with time zone NOT NULL DEFAULT now()
);
ALTER TABLE public.leave_requests ENABLE ROW LEVEL SECURITY;
COMMENT ON TABLE public.leave_requests IS 'Stores leave requests submitted by users.';

-- Tabel untuk menyimpan rekapitulasi saldo cuti tahunan setiap pengguna.
CREATE TABLE public.leave_balances (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    year integer NOT NULL,
    total_days integer NOT NULL DEFAULT 12,
    used_days integer NOT NULL DEFAULT 0,
    UNIQUE (user_id, year)
);
ALTER TABLE public.leave_balances ENABLE ROW LEVEL SECURITY;
COMMENT ON TABLE public.leave_balances IS 'Stores annual leave balance for each user.';

-- Tabel untuk notifikasi admin.
CREATE TABLE public.notifications (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE, -- Admin user_id
    leave_request_id bigint NOT NULL REFERENCES public.leave_requests(id) ON DELETE CASCADE,
    message text NOT NULL,
    is_read boolean NOT NULL DEFAULT false,
    created_at timestamp with time zone NOT NULL DEFAULT now()
);
ALTER TABLE public.notifications ENABLE ROW LEVEL SECURITY;
COMMENT ON TABLE public.notifications IS 'Notifications for admins about new leave requests.';


