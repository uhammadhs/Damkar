-- ### TABLES ###

-- Create profiles table
-- This table is populated by a trigger when a new user signs up.
CREATE TABLE public.profiles (
    id uuid NOT NULL PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    name character varying,
    id_pjlp character varying UNIQUE,
    phone character varying,
    email character varying,
    avatar_url character varying,
    role character varying DEFAULT 'anggota',
    updated_at timestamp with time zone
);
COMMENT ON TABLE public.profiles IS 'Holds public-facing profile information for each user.';
COMMENT ON COLUMN public.profiles.id IS 'References the auth.users table.';

-- Create leave_requests table
CREATE TABLE public.leave_requests (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    start_date date NOT NULL,
    end_date date NOT NULL,
    duration integer NOT NULL,
    title character varying NOT NULL,
    reason text,
    status character varying DEFAULT 'Menunggu'::character varying NOT NULL,
    attachment_url text,
    is_read_by_user boolean DEFAULT false NOT NULL,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    updated_at timestamp with time zone DEFAULT now() NOT NULL
);
COMMENT ON TABLE public.leave_requests IS 'Stores all leave requests from users.';

-- Create leave_balances table
CREATE TABLE public.leave_balances (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    year integer NOT NULL,
    total_days integer DEFAULT 12 NOT NULL,
    used_days integer DEFAULT 0 NOT NULL,
    CONSTRAINT leave_balances_user_id_year_key UNIQUE (user_id, year)
);
COMMENT ON TABLE public.leave_balances IS 'Tracks annual leave balances for each user.';


-- ### RLS (ROW LEVEL SECURITY) ###

-- Enable RLS for all tables
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.leave_requests ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.leave_balances ENABLE ROW LEVEL SECURITY;

-- Profiles Policies
-- Users can view their own profile.
CREATE POLICY "Users can view their own profile" ON public.profiles FOR SELECT USING (auth.uid() = id);
-- Users can update their own profile.
CREATE POLICY "Users can update their own profile" ON public.profiles FOR UPDATE USING (auth.uid() = id) WITH CHECK (auth.uid() = id);
-- Admins have full access to all profiles.
CREATE POLICY "Admins can manage all profiles" ON public.profiles FOR ALL USING ('admin' = (SELECT public.get_user_role()));


-- Leave Requests Policies
-- Users can view their own leave requests.
CREATE POLICY "Users can view their own leave requests" ON public.leave_requests FOR SELECT USING (auth.uid() = user_id);
-- Users can insert their own leave requests.
CREATE POLICY "Users can insert their own leave requests" ON public.leave_requests FOR INSERT WITH CHECK (auth.uid() = user_id);
-- Admins have full access to all leave requests.
CREATE POLICY "Admins can manage all leave requests" ON public.leave_requests FOR ALL USING ('admin' = (SELECT public.get_user_role()));


-- Leave Balances Policies
-- Users can view their own leave balance.
CREATE POLICY "Users can view their own leave balance" ON public.leave_balances FOR SELECT USING (auth.uid() = user_id);
-- Admins have full access to all leave balances.
CREATE POLICY "Admins can manage all leave balances" ON public.leave_balances FOR ALL USING ('admin' = (SELECT public.get_user_role()));


-- ### FUNCTIONS & TRIGGERS ###

-- Function to get a user's role from their profile
CREATE OR REPLACE FUNCTION public.get_user_role()
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  RETURN (SELECT role FROM public.profiles WHERE id = auth.uid());
END;
$$;


-- Function to create a user profile when a new user signs up in auth.users
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  INSERT INTO public.profiles (id, name, id_pjlp, phone, email, role, avatar_url)
  VALUES (
    new.id,
    new.raw_user_meta_data->>'name',
    new.raw_user_meta_data->>'id_pjlp',
    new.raw_user_meta_data->>'phone',
    new.email,
    new.raw_user_meta_data->>'role', -- This will be null for self-signup, 'admin' if set by admin
    new.raw_user_meta_data->>'avatar_url'
  );
  RETURN new;
END;
$$;

-- Trigger to call handle_new_user on new user creation
CREATE TRIGGER on_auth_user_created
AFTER INSERT ON auth.users
FOR EACH ROW EXECUTE PROCEDURE public.handle_new_user();


-- Function to update the leave balance when a request is approved.
CREATE OR REPLACE FUNCTION public.update_leave_balance()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  request_duration integer;
  request_year integer;
BEGIN
  -- Only run if the status is changed TO 'Disetujui'
  IF new.status = 'Disetujui' AND old.status != 'Disetujui' THEN
    request_duration := new.duration;
    request_year := EXTRACT(year FROM new.start_date);

    -- Update the used_days for the corresponding year
    UPDATE public.leave_balances
    SET used_days = used_days + request_duration
    WHERE user_id = new.user_id AND year = request_year;
  END IF;

  -- If a request is changed FROM 'Disetujui' to something else (e.g., cancelled), revert the days.
  IF old.status = 'Disetujui' AND new.status != 'Disetujui' THEN
    request_duration := old.duration;
    request_year := EXTRACT(year FROM old.start_date);

    UPDATE public.leave_balances
    SET used_days = used_days - request_duration
    WHERE user_id = old.user_id AND year = request_year;
  END IF;
  
  RETURN new;
END;
$$;

-- Trigger to call update_leave_balance when a leave request is updated
CREATE TRIGGER trigger_update_leave_balance_on_approve
AFTER UPDATE ON public.leave_requests
FOR EACH ROW EXECUTE PROCEDURE public.update_leave_balance();


-- Function to create leave balance if it doesn't exist for the year
CREATE OR REPLACE FUNCTION public.create_leave_balance_if_not_exists()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  request_year integer;
BEGIN
  request_year := EXTRACT(year FROM new.start_date);
  
  -- Check if a balance record for that user and year already exists.
  -- If not, create one.
  IF NOT EXISTS (
    SELECT 1 FROM public.leave_balances
    WHERE user_id = new.user_id AND year = request_year
  ) THEN
    INSERT INTO public.leave_balances (user_id, year, total_days, used_days)
    VALUES (new.user_id, request_year, 12, 0);
  END IF;
  
  RETURN new;
END;
$$;

-- Trigger to run the check on every new leave request submission.
CREATE TRIGGER trigger_check_leave_balance_on_insert
BEFORE INSERT ON public.leave_requests
FOR EACH ROW EXECUTE PROCEDURE public.create_leave_balance_if_not_exists();
