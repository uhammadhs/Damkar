
-- ### PROFILES ###
-- Table to store user profiles, extending the auth.users table
create table public.profiles (
  id uuid references auth.users on delete cascade not null primary key,
  updated_at timestamp with time zone,
  name varchar(255),
  id_pjlp varchar(50) unique,
  phone varchar(20),
  email varchar(255) unique,
  avatar_url text,
  role text default 'anggota'
);

-- Row Level Security for profiles
alter table public.profiles enable row level security;
create policy "Public profiles are viewable by everyone." on public.profiles for select using (true);
create policy "Users can insert their own profile." on public.profiles for insert with check (auth.uid() = id);
create policy "Users can update own profile." on public.profiles for update using (auth.uid() = id);
create policy "Admins can do anything." on public.profiles for all using (get_user_role() = 'admin');

-- Trigger to create a profile for a new user
create function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.profiles (id, name, id_pjlp, phone, email, role)
  values (
    new.id,
    new.raw_user_meta_data->>'name',
    new.raw_user_meta_data->>'id_pjlp',
    new.raw_user_meta_data->>'phone',
    new.email,
    'anggota' -- Default role for new sign-ups
  );
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

-- Trigger to automatically create a leave balance entry for a new user for the current year
create or replace function public.on_new_user_create_leave_balance()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  -- Insert a leave balance for the current year when a new profile is created
  insert into public.leave_balances (user_id, year, total_days, used_days)
  values (new.id, date_part('year', now()), 12, 0);
  return new;
end;
$$;

create trigger on_profile_created_create_balance
  after insert on public.profiles
  for each row execute procedure public.on_new_user_create_leave_balance();


-- ### LEAVE BALANCES ###
-- Table to store yearly leave balances for each user
create table public.leave_balances (
  id bigint generated by default as identity primary key,
  user_id uuid references public.profiles on delete cascade not null,
  year int not null,
  total_days int not null default 12,
  used_days int not null default 0,
  unique (user_id, year)
);

-- Row Level Security for leave_balances
alter table public.leave_balances enable row level security;
create policy "Users can view their own leave balance." on public.leave_balances for select using (auth.uid() = user_id);
create policy "Admins can view all leave balances." on public.leave_balances for select using (get_user_role() = 'admin');
create policy "Admins can update all leave balances." on public.leave_balances for update using (get_user_role() = 'admin');
create policy "Admins can insert leave balances." on public.leave_balances for insert with check (get_user_role() = 'admin');

-- ### LEAVE REQUESTS ###
-- Table to store leave requests from users
create table public.leave_requests (
  id bigint generated by default as identity primary key,
  user_id uuid references public.profiles on delete cascade not null,
  start_date date not null,
  end_date date not null,
  duration int not null,
  title varchar(255) not null,
  reason text,
  status varchar(50) not null default 'Menunggu',
  attachment_url text,
  is_read_by_user boolean not null default false,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  updated_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Row Level Security for leave_requests
alter table public.leave_requests enable row level security;
create policy "Users can view their own leave requests." on public.leave_requests for select using (auth.uid() = user_id);
create policy "Users can insert their own leave requests." on public.leave_requests for insert with check (auth.uid() = user_id);
create policy "Admins can view all leave requests." on public.leave_requests for select using (get_user_role() = 'admin');
create policy "Admins can update all leave requests." on public.leave_requests for update using (get_user_role() = 'admin');

-- Trigger to set updated_at timestamp automatically
create trigger handle_updated_at
  before update on public.leave_requests
  for each row
  execute procedure moddatetime(updated_at);

-- ### NOTIFICATIONS ###
-- Table to store notifications for admins
create table public.notifications (
  id bigint generated by default as identity primary key,
  user_id uuid references public.profiles on delete cascade not null, -- The user to be notified (the admin)
  leave_request_id bigint references public.leave_requests on delete cascade not null,
  message text not null,
  is_read boolean not null default false,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Row Level Security for notifications
alter table public.notifications enable row level security;
create policy "Admins can view their own notifications." on public.notifications for select using (auth.uid() = user_id and get_user_role() = 'admin');
create policy "Admins can update their own notifications." on public.notifications for update using (auth.uid() = user_id and get_user_role() = 'admin');

-- Function to create notification for all admins when a new leave request is submitted
create or replace function public.create_admin_notification_for_new_leave()
returns trigger
language plpgsql
security definer set search_path = public
as $$
declare
  admin_record record;
  submitter_name text;
begin
  -- Get the name of the user who submitted the request
  select name into submitter_name from public.profiles where id = new.user_id;
  
  -- If name is not found, use a default
  if submitter_name is null then
    submitter_name := 'Seorang anggota';
  end if;

  -- Loop through all admins and create a notification for each
  for admin_record in select id from public.profiles where role = 'admin'
  loop
    insert into public.notifications (user_id, leave_request_id, message)
    values (admin_record.id, new.id, submitter_name || ' mengajukan cuti baru: "' || new.title || '".');
  end loop;
  
  return new;
end;
$$;

-- Trigger to call the notification function
create trigger on_leave_request_created_notify_admins
  after insert on public.leave_requests
  for each row execute procedure public.create_admin_notification_for_new_leave();


-- ### HELPER FUNCTIONS ###
-- Function to get the role of the currently authenticated user
create or replace function public.get_user_role()
returns text
language plpgsql
security definer set search_path = public
as $$
declare
  user_role text;
begin
  if auth.uid() is null then
    return 'anon';
  end if;
  
  select role into user_role from public.profiles where id = auth.uid();
  return user_role;
end;
$$;

-- Function to handle resetting leave balances at the start of a new year
-- This function can be run by a cron job (e.g., using Supabase's pg_cron)
create or replace function public.handle_new_year_leave_balances()
returns void
language plpgsql
as $$
declare
  member record;
  current_year int := date_part('year', now());
begin
  for member in select id from public.profiles where role = 'anggota'
  loop
    -- Check if a balance for the current year already exists for this member
    if not exists (select 1 from public.leave_balances where user_id = member.id and year = current_year) then
      -- If not, insert a new balance for the new year
      insert into public.leave_balances(user_id, year, total_days, used_days)
      values (member.id, current_year, 12, 0);
    end if;
  end loop;
end;
$$;


