-- Kebijakan untuk tabel 'profiles'
DROP POLICY IF EXISTS "Admin can read all profiles." ON public.profiles;
CREATE POLICY "Admin can read all profiles." ON public.profiles FOR SELECT TO authenticated USING (public.get_user_role () = 'admin');

DROP POLICY IF EXISTS "Users can view their own profile." ON public.profiles;
CREATE POLICY "Users can view their own profile." ON public.profiles FOR SELECT TO authenticated USING (auth.uid () = id);

DROP POLICY IF EXISTS "Users can update their own profile." ON public.profiles;
CREATE POLICY "Users can update their own profile." ON public.profiles FOR UPDATE TO authenticated USING (auth.uid () = id);

-- Kebijakan untuk tabel 'leave_balances'
DROP POLICY IF EXISTS "Admin can read all leave balances." ON public.leave_balances;
CREATE POLICY "Admin can read all leave balances." ON public.leave_balances FOR SELECT TO authenticated USING (public.get_user_role () = 'admin');

DROP POLICY IF EXISTS "Users can view their own leave balance." ON public.leave_balances;
CREATE POLICY "Users can view their own leave balance." ON public.leave_balances FOR SELECT TO authenticated USING (auth.uid () = user_id);

-- Kebijakan untuk tabel 'leave_requests'
DROP POLICY IF EXISTS "Admin can read all leave requests." ON public.leave_requests;
CREATE POLICY "Admin can read all leave requests." ON public.leave_requests FOR SELECT TO authenticated USING (public.get_user_role () = 'admin');

DROP POLICY IF EXISTS "Admin can update leave requests." ON public.leave_requests;
CREATE POLICY "Admin can update leave requests." ON public.leave_requests FOR UPDATE TO authenticated USING (public.get_user_role () = 'admin');

