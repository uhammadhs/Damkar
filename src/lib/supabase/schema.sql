-- 3. FUNGSI DATABASE (RPC & HELPERS)
-- ------------------------------------------------------------------------------------------------
-- Fungsi untuk mendapatkan peran (role) pengguna yang sedang login.
-- Digunakan di dalam kebijakan RLS.
CREATE OR REPLACE FUNCTION public.get_user_role () RETURNS TEXT AS $$
DECLARE
  user_role TEXT;
BEGIN
  SELECT
    role INTO user_role
  FROM
    public.profiles
  WHERE
    id = auth.uid ();
  RETURN user_role;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Fungsi untuk login menggunakan ID PJLP dan password.
-- Mengurangi jumlah panggilan dari klien, meningkatkan kecepatan & keamanan.
CREATE OR REPLACE FUNCTION public.login_with_id_pjlp (p_id_pjlp TEXT, p_password TEXT) RETURNS JSON AS $$
DECLARE
    user_record RECORD;
    token TEXT;
    user_data JSON;
    result JSON;
BEGIN
    -- Cari pengguna berdasarkan ID PJLP
    SELECT id, email, role INTO user_record
    FROM public.profiles
    WHERE id_pjlp = p_id_pjlp;

    -- Jika tidak ditemukan, kembalikan error
    IF user_record IS NULL THEN
        RETURN json_build_object('error', 'ID PJLP tidak ditemukan.');
    END IF;

    -- Lakukan sign-in menggunakan fungsi bawaan Supabase
    SELECT sign_in(user_record.email, p_password) INTO token;

    -- Jika token null (login gagal), kembalikan error
    IF token IS NULL THEN
        RETURN json_build_object('error', 'Password salah.');
    END IF;

    -- Jika berhasil, siapkan data pengguna untuk dikembalikan
    user_data := json_build_object(
        'user_id', user_record.id,
        'role', user_record.role,
        'email', user_record.email
    );

    -- Kembalikan data pengguna
    RETURN user_data;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Fungsi yang akan dipanggil oleh trigger saat ada pengguna baru mendaftar.
CREATE OR REPLACE FUNCTION public.handle_new_user () RETURNS TRIGGER AS $$
DECLARE
  current_year INT := EXTRACT(YEAR FROM NOW());
BEGIN
  -- 1. Sisipkan data dari auth.users ke public.profiles
  INSERT INTO public.profiles (id, name, id_pjlp, phone, email, role)
  VALUES (
    new.id,
    new.raw_user_meta_data ->> 'name',
    new.raw_user_meta_data ->> 'id_pjlp',
    new.raw_user_meta_data ->> 'phone',
    new.email,
    'anggota' -- Default role
  );

  -- 2. Buat entri saldo cuti awal untuk tahun berjalan
  INSERT INTO public.leave_balances (user_id, year, total_days, used_days)
  VALUES (new.id, current_year, 12, 0);
  
  RETURN new;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Fungsi untuk membuat notifikasi kepada semua admin saat ada pengajuan cuti baru.
CREATE OR REPLACE FUNCTION public.notify_admin_on_new_leave() RETURNS TRIGGER AS $$
DECLARE
    admin_record RECORD;
    leave_user_name TEXT;
BEGIN
    -- Ambil nama pengguna yang mengajukan cuti
    SELECT name INTO leave_user_name FROM public.profiles WHERE id = NEW.user_id;

    -- Loop melalui semua admin dan buat notifikasi untuk mereka
    FOR admin_record IN SELECT id FROM public.profiles WHERE role = 'admin' LOOP
        INSERT INTO public.notifications (user_id, leave_request_id, message)
        VALUES (admin_record.id, NEW.id, leave_user_name || ' telah mengajukan cuti baru: "' || NEW.title || '"');
    END LOOP;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Fungsi untuk reset saldo cuti tahunan, dipanggil oleh CRON Job.
CREATE OR REPLACE FUNCTION public.handle_new_year_leave_balances () RETURNS VOID AS $$
DECLARE
  user_record RECORD;
  current_year INT := EXTRACT(YEAR FROM NOW());
BEGIN
  FOR user_record IN
  SELECT
    id
  FROM
    public.profiles LOOP
    -- Sisipkan saldo cuti baru untuk tahun ini, abaikan jika sudah ada
    INSERT INTO public.leave_balances (user_id, year, total_days, used_days)
      VALUES (user_record.id, current_year, 12, 0)
    ON CONFLICT (user_id, year)
      DO NOTHING;
  END LOOP;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;


