
-- ----------------------------
-- Konfigurasi Awal
-- ----------------------------
-- Nonaktifkan trigger untuk sementara agar tidak ada gangguan saat membuat tabel
ALTER ROLE supabase_admin SET pgrst.db_pre_request = '';
NOTIFY pgrst, 'reload config';

-- ----------------------------
-- Tabel: profiles
-- ----------------------------
-- Menyimpan data profil pengguna yang terhubung dengan tabel auth.users
CREATE TABLE public.profiles (
    id uuid NOT NULL PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    updated_at timestamp with time zone,
    name character varying,
    id_pjlp character varying UNIQUE,
    phone character varying,
    avatar_url character varying,
    email character varying,
    role character varying DEFAULT 'anggota'
);

-- Kebijakan Keamanan (RLS) untuk tabel profiles
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;

-- Pengguna bisa melihat semua profil (untuk admin)
CREATE POLICY "Profiles are viewable by everyone." ON public.profiles
    FOR SELECT USING (true);

-- Pengguna bisa memperbarui profil mereka sendiri
CREATE POLICY "Users can update their own profile." ON public.profiles
    FOR UPDATE USING (auth.uid() = id);

-- Admin bisa menambah, mengubah, dan menghapus profil
CREATE POLICY "Admins can manage all profiles." ON public.profiles
    FOR ALL USING (public.get_user_role() = 'admin') WITH CHECK (public.get_user_role() = 'admin');

-- ----------------------------
-- Tabel: leave_requests
-- ----------------------------
-- Menyimpan semua data pengajuan cuti dari pengguna
CREATE TABLE public.leave_requests (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone not null default now(),
    user_id uuid not null references public.profiles(id) on delete cascade,
    start_date date not null,
    end_date date not null,
    duration integer not null,
    title character varying not null,
    reason text,
    status character varying not null default 'Menunggu',
    attachment_url character varying,
    updated_at timestamp with time zone not null default now(),
    is_read_by_user boolean not null default false
);

-- Kebijakan Keamanan (RLS) untuk tabel leave_requests
ALTER TABLE public.leave_requests ENABLE ROW LEVEL SECURITY;

-- Pengguna bisa membuat pengajuan untuk diri mereka sendiri
CREATE POLICY "Users can insert their own leave requests." ON public.leave_requests
    FOR INSERT WITH CHECK (auth.uid() = user_id);

-- Pengguna bisa melihat pengajuan mereka sendiri
CREATE POLICY "Users can view their own leave requests." ON public.leave_requests
    FOR SELECT USING (auth.uid() = user_id);
    
-- Pengguna bisa memperbarui status notifikasi mereka
CREATE POLICY "Users can update read status for their own requests." ON public.leave_requests
    FOR UPDATE USING (auth.uid() = user_id) WITH CHECK (auth.uid() = user_id);

-- Admin bisa melihat semua pengajuan cuti
CREATE POLICY "Admins can view all leave requests." ON public.leave_requests
    FOR SELECT USING (public.get_user_role() = 'admin');

-- Admin bisa memperbarui status pengajuan cuti
CREATE POLICY "Admins can update leave requests." ON public.leave_requests
    FOR UPDATE USING (public.get_user_role() = 'admin');


-- ----------------------------
-- Tabel: leave_balances
-- ----------------------------
-- Menyimpan rekap saldo cuti tahunan setiap pengguna
CREATE TABLE public.leave_balances (
    id bigint generated by default as identity primary key,
    user_id uuid not null references public.profiles(id) on delete cascade,
    year integer not null,
    total_days integer not null default 12,
    used_days integer not null default 0,
    CONSTRAINT unique_user_year UNIQUE (user_id, year)
);

-- Kebijakan Keamanan (RLS) untuk tabel leave_balances
ALTER TABLE public.leave_balances ENABLE ROW LEVEL SECURITY;

-- Pengguna bisa melihat saldo cuti mereka sendiri
CREATE POLICY "Users can view their own leave balances." ON public.leave_balances
    FOR SELECT USING (auth.uid() = user_id);

-- Admin bisa melihat semua saldo cuti
CREATE POLICY "Admins can view all leave balances." ON public.leave_balances
    FOR SELECT USING (public.get_user_role() = 'admin');

-- Admin dapat mengelola semua saldo cuti (untuk penyesuaian manual jika diperlukan)
CREATE POLICY "Admins can manage all leave balances." ON public.leave_balances
    FOR ALL USING (public.get_user_role() = 'admin');


-- ----------------------------
-- Tabel: notifications
-- ----------------------------
-- Menyimpan notifikasi untuk admin ketika ada pengajuan baru
CREATE TABLE public.notifications (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone not null default now(),
    leave_request_id bigint not null references public.leave_requests(id) on delete cascade,
    user_id uuid not null references public.profiles(id) on delete cascade, -- admin's user id
    message character varying not null,
    is_read boolean not null default false
);

-- Kebijakan Keamanan (RLS) untuk tabel notifications
ALTER TABLE public.notifications ENABLE ROW LEVEL SECURITY;

-- Admin bisa melihat notifikasi yang ditujukan untuk mereka
CREATE POLICY "Admins can view their own notifications." ON public.notifications
    FOR SELECT USING (auth.uid() = user_id AND public.get_user_role() = 'admin');

-- Admin bisa menandai notifikasi mereka sebagai sudah dibaca
CREATE POLICY "Admins can update their own notifications." ON public.notifications
    FOR UPDATE USING (auth.uid() = user_id AND public.get_user_role() = 'admin');


-- ----------------------------
-- Fungsi dan Trigger
-- ----------------------------

-- 1. Fungsi untuk mendapatkan peran pengguna (get_user_role)
CREATE OR REPLACE FUNCTION public.get_user_role()
RETURNS text
LANGUAGE plpgsql
AS $$
BEGIN
  RETURN (
    SELECT role FROM public.profiles WHERE id = auth.uid()
  );
END;
$$;

-- 2. Fungsi untuk membuat profil baru saat pengguna mendaftar (handle_new_user)
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
  INSERT INTO public.profiles (id, name, id_pjlp, phone, email, role)
  VALUES (
    new.id, 
    new.raw_user_meta_data->>'name',
    new.raw_user_meta_data->>'id_pjlp',
    new.raw_user_meta_data->>'phone',
    new.email,
    'anggota' -- Default role
  );
  RETURN new;
END;
$$;

-- Trigger yang memanggil handle_new_user setelah pengguna baru ditambahkan di auth.users
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE PROCEDURE public.handle_new_user();

-- 3. Fungsi untuk membuat saldo cuti awal bagi pengguna baru
CREATE OR REPLACE FUNCTION public.on_new_user_create_leave_balance()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  current_year integer;
BEGIN
  -- Dapatkan tahun saat ini
  current_year := EXTRACT(YEAR FROM now());
  
  -- Buat entri saldo cuti untuk tahun berjalan
  INSERT INTO public.leave_balances (user_id, year, total_days, used_days)
  VALUES (NEW.id, current_year, 12, 0);
  
  RETURN NEW;
END;
$$;

-- Trigger yang memanggil fungsi di atas setelah profil baru dibuat
CREATE TRIGGER on_profile_created_add_balance
  AFTER INSERT ON public.profiles
  FOR EACH ROW EXECUTE PROCEDURE public.on_new_user_create_leave_balance();

-- 4. Fungsi untuk membuat notifikasi untuk semua admin saat ada pengajuan cuti baru
CREATE OR REPLACE FUNCTION public.create_admin_notification_for_new_leave()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    admin_record RECORD;
    requesting_user_name TEXT;
BEGIN
    -- Dapatkan nama pengguna yang mengajukan cuti
    SELECT name INTO requesting_user_name FROM public.profiles WHERE id = NEW.user_id;

    -- Ulangi untuk setiap admin dan buat notifikasi
    FOR admin_record IN SELECT id FROM public.profiles WHERE role = 'admin'
    LOOP
        INSERT INTO public.notifications (leave_request_id, user_id, message)
        VALUES (NEW.id, admin_record.id, requesting_user_name || ' telah mengajukan cuti baru: "' || NEW.title || '".');
    END LOOP;

    RETURN NEW;
END;
$$;

-- Trigger yang memanggil fungsi di atas setelah pengajuan baru dibuat
CREATE TRIGGER on_leave_request_created_notify_admins
  AFTER INSERT ON public.leave_requests
  FOR EACH ROW EXECUTE PROCEDURE public.create_admin_notification_for_new_leave();

