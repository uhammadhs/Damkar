-- ----------------------------------------------------------------
-- 1. PEMBUATAN TABEL (TABLE CREATION)
-- ----------------------------------------------------------------
-- Fondasi dasar untuk menyimpan semua data aplikasi.

CREATE TABLE public.profiles (
    id uuid NOT NULL PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    name character varying,
    id_pjlp character varying UNIQUE,
    phone character varying,
    email character varying UNIQUE,
    avatar_url character varying,
    role character varying DEFAULT 'anggota'::character varying,
    updated_at timestamp with time zone
);

CREATE TABLE public.leave_requests (
    id bigint NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    user_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    title character varying NOT NULL,
    reason text,
    start_date date NOT NULL,
    end_date date NOT NULL,
    duration integer NOT NULL,
    status character varying DEFAULT 'Menunggu'::character varying NOT NULL,
    attachment_url character varying,
    is_read_by_user boolean DEFAULT false NOT NULL,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    updated_at timestamp with time zone DEFAULT now() NOT NULL
);

CREATE TABLE public.leave_balances (
    id bigint NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    user_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    year integer NOT NULL,
    total_days integer DEFAULT 12 NOT NULL,
    used_days integer DEFAULT 0 NOT NULL,
    UNIQUE(user_id, year)
);

CREATE TABLE public.notifications (
    id bigint NOT NULL PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    user_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    leave_request_id bigint NOT NULL REFERENCES public.leave_requests(id) ON DELETE CASCADE,
    message character varying NOT NULL,
    is_read boolean DEFAULT false NOT NULL,
    created_at timestamp with time zone DEFAULT now() NOT NULL
);

-- ----------------------------------------------------------------
-- 2. OPTIMISASI PERFORMA (INDEXING)
-- ----------------------------------------------------------------
-- Membuat indeks untuk mempercepat query pada kolom yang sering dicari.

CREATE INDEX ON public.leave_requests (user_id);
CREATE INDEX ON public.leave_requests (status);
CREATE INDEX ON public.leave_balances (user_id, year);
CREATE INDEX ON public.notifications (user_id);
CREATE INDEX ON public.profiles (id_pjlp);
CREATE INDEX ON public.profiles (role);

-- ----------------------------------------------------------------
-- 3. PEMBUATAN FUNGSI (FUNCTIONS)
-- ----------------------------------------------------------------
-- Logika bisnis yang akan digunakan oleh RLS Policies dan Triggers.

-- Fungsi untuk mendapatkan peran pengguna saat ini (digunakan di RLS).
CREATE OR REPLACE FUNCTION public.get_user_role()
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER -- Penting agar bisa membaca tabel internal auth
SET search_path = public
AS $$
BEGIN
  IF auth.uid() IS NULL THEN
    RETURN 'anon';
  ELSE
    RETURN (
      SELECT role
      FROM public.profiles
      WHERE id = auth.uid()
      LIMIT 1
    );
  END IF;
END;
$$;

-- Fungsi yang dipanggil oleh trigger saat ada user baru di `auth.users`.
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  current_year integer;
BEGIN
  -- Membuat profil baru di tabel `public.profiles`
  INSERT INTO public.profiles (id, name, id_pjlp, phone, email, role)
  VALUES (
    new.id,
    new.raw_user_meta_data->>'name',
    new.raw_user_meta_data->>'id_pjlp',
    new.raw_user_meta_data->>'phone',
    new.email,
    'anggota' -- Default role untuk semua pendaftar baru
  );

  -- Membuat saldo cuti awal untuk tahun berjalan
  SELECT date_part('year', CURRENT_DATE) INTO current_year;
  INSERT INTO public.leave_balances (user_id, year, total_days, used_days)
  VALUES (new.id, current_year, 12, 0);
  
  RETURN new;
END;
$$;

-- Fungsi untuk membuat notifikasi kepada semua admin saat ada pengajuan cuti baru.
CREATE OR REPLACE FUNCTION public.create_admin_notification_for_new_leave()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  admin_record record;
  applicant_name text;
BEGIN
  -- Dapatkan nama pemohon
  SELECT name INTO applicant_name FROM public.profiles WHERE id = NEW.user_id;

  -- Loop melalui semua admin dan buat notifikasi untuk mereka
  FOR admin_record IN SELECT id FROM public.profiles WHERE role = 'admin'
  LOOP
    INSERT INTO public.notifications (user_id, leave_request_id, message)
    VALUES (admin_record.id, NEW.id, applicant_name || ' telah mengajukan cuti baru: "' || NEW.title || '".');
  END LOOP;
  
  RETURN NEW;
END;
$$;

-- Fungsi untuk reset saldo cuti tahunan untuk semua anggota.
CREATE OR REPLACE FUNCTION public.handle_new_year_leave_balances()
RETURNS void
LANGUAGE plpgsql
AS $$
DECLARE
  user_record record;
  current_year integer;
BEGIN
  -- Dapatkan tahun saat ini
  SELECT date_part('year', CURRENT_DATE) INTO current_year;

  -- Loop melalui semua pengguna dengan peran 'anggota'
  FOR user_record IN SELECT id FROM public.profiles WHERE role = 'anggota'
  LOOP
    -- Periksa apakah sudah ada entri saldo untuk tahun ini
    IF NOT EXISTS (SELECT 1 FROM public.leave_balances WHERE user_id = user_record.id AND year = current_year) THEN
      -- Jika tidak ada, buat entri saldo cuti baru untuk tahun ini
      INSERT INTO public.leave_balances (user_id, year, total_days, used_days)
      VALUES (user_record.id, current_year, 12, 0);
    END IF;
  END LOOP;
END;
$$;

-- ----------------------------------------------------------------
-- 4. KEAMANAN DATA (ROW LEVEL SECURITY)
-- ----------------------------------------------------------------
-- Mengaktifkan RLS dan mendefinisikan kebijakan akses untuk setiap tabel.

-- Tabel Profiles
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Users can view their own profile" ON public.profiles FOR SELECT USING (auth.uid() = id);
CREATE POLICY "Users can update their own profile" ON public.profiles FOR UPDATE USING (auth.uid() = id);
CREATE POLICY "Admins can view all profiles" ON public.profiles FOR SELECT TO authenticated USING (get_user_role() = 'admin');
CREATE POLICY "Admins can manage all profiles" ON public.profiles FOR ALL TO authenticated USING (get_user_role() = 'admin') WITH CHECK (get_user_role() = 'admin');

-- Tabel Leave Balances
ALTER TABLE public.leave_balances ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Users can view their own leave balances" ON public.leave_balances FOR SELECT USING (auth.uid() = user_id);
CREATE POLICY "Admins can view all leave balances" ON public.leave_balances FOR SELECT TO authenticated USING (get_user_role() = 'admin');
CREATE POLICY "Server can manage leave balances" ON public.leave_balances FOR ALL USING (true); -- Dikelola oleh trigger/fungsi server

-- Tabel Leave Requests
ALTER TABLE public.leave_requests ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Users can create and view their own leave requests" ON public.leave_requests FOR ALL USING (auth.uid() = user_id);
CREATE POLICY "Admins can view all leave requests" ON public.leave_requests FOR SELECT TO authenticated USING (get_user_role() = 'admin');
CREATE POLICY "Admins can update leave requests" ON public.leave_requests FOR UPDATE TO authenticated USING (get_user_role() = 'admin');

-- Tabel Notifications
ALTER TABLE public.notifications ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Users can view their own notifications" ON public.notifications FOR SELECT USING (auth.uid() = user_id);
CREATE POLICY "Admins can update their own notifications" ON public.notifications FOR UPDATE TO authenticated USING (auth.uid() = user_id AND get_user_role() = 'admin');
CREATE POLICY "Server can create notifications" ON public.notifications FOR INSERT USING (true);


-- ----------------------------------------------------------------
-- 5. OTOMATISASI PROSES (TRIGGERS)
-- ----------------------------------------------------------------
-- Pemicu yang menjalankan fungsi secara otomatis berdasarkan event di database.

-- Trigger untuk menjalankan handle_new_user() setiap kali ada user baru dibuat di auth.users.
CREATE OR REPLACE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

-- Trigger untuk menjalankan create_admin_notification_for_new_leave() setiap ada pengajuan cuti baru.
CREATE OR REPLACE TRIGGER on_leave_request_created
  AFTER INSERT ON public.leave_requests
  FOR EACH ROW EXECUTE FUNCTION public.create_admin_notification_for_new_leave();

