-- -----------------------------------------------------------------
--  1. Create Tables
-- -----------------------------------------------------------------

-- Profiles Table
-- Stores public user data. Users can read their own profile and admins can read all.
create table public.profiles (
  id uuid not null references auth.users on delete cascade,
  updated_at timestamp with time zone,
  name text,
  avatar_url text,
  role text default 'anggota',
  id_pjlp text,
  phone text,
  email text,
  primary key (id),
  unique (id_pjlp)
);
comment on table public.profiles is 'Stores public-facing profile information for each user.';

-- Leave Requests Table
-- Stores leave requests from users.
create table public.leave_requests (
  id bigint generated by default as identity,
  created_at timestamp with time zone not null default now(),
  user_id uuid not null references public.profiles on delete cascade,
  title text not null,
  reason text,
  start_date date not null,
  end_date date not null,
  duration integer not null,
  status text not null default 'Menunggu',
  attachment_url text,
  is_read_by_user boolean not null default true,
  updated_at timestamp with time zone not null default now(),
  primary key (id)
);
comment on table public.leave_requests is 'Stores leave requests submitted by users.';

-- Leave Balances Table
-- Stores the annual leave balance for each user.
create table public.leave_balances (
  id bigint generated by default as identity,
  user_id uuid not null references public.profiles on delete cascade,
  year integer not null,
  total_days integer not null default 12,
  used_days integer not null default 0,
  primary key (id),
  unique (user_id, year)
);
comment on table public.leave_balances is 'Stores the annual leave balance for each user.';

-- Notifications Table
-- Stores notifications for users and admins.
create table public.notifications (
  id bigint generated by default as identity,
  created_at timestamp with time zone not null default now(),
  user_id uuid not null references public.profiles on delete cascade,
  leave_request_id bigint not null references public.leave_requests on delete cascade,
  message text not null,
  is_read boolean not null default false,
  primary key (id)
);
comment on table public.notifications is 'Notifications for new leave requests for admins.';

-- -----------------------------------------------------------------
--  2. Enable Row Level Security (RLS)
-- -----------------------------------------------------------------
alter table public.profiles enable row level security;
alter table public.leave_requests enable row level security;
alter table public.leave_balances enable row level security;
alter table public.notifications enable row level security;

-- -----------------------------------------------------------------
--  3. Create RLS Policies
-- -----------------------------------------------------------------

-- Profiles Policies
create policy "Users can view their own profile." on public.profiles for select using (auth.uid() = id);
create policy "Users can update their own profile." on public.profiles for update using (auth.uid() = id) with check (auth.uid() = id);
create policy "Admins can view all profiles." on public.profiles for select using (public.get_user_role() = 'admin');
create policy "Admins can update all profiles." on public.profiles for update using (public.get_user_role() = 'admin') with check (public.get_user_role() = 'admin');

-- Leave Requests Policies
create policy "Users can view their own leave requests." on public.leave_requests for select using (auth.uid() = user_id);
create policy "Users can create their own leave requests." on public.leave_requests for insert with check (auth.uid() = user_id);
create policy "Users can update their own unread leave requests." on public.leave_requests for update using (auth.uid() = user_id) with check (auth.uid() = user_id);
create policy "Admins can view all leave requests." on public.leave_requests for select using (public.get_user_role() = 'admin');
create policy "Admins can update all leave requests." on public.leave_requests for update using (public.get_user_role() = 'admin') with check (public.get_user_role() = 'admin');

-- Leave Balances Policies
create policy "Users can view their own leave balances." on public.leave_balances for select using (auth.uid() = user_id);
create policy "Admins can view all leave balances." on public.leave_balances for select using (public.get_user_role() = 'admin');
create policy "Allow insert for service_role only" on public.leave_balances for insert with check (auth.role() = 'service_role');
create policy "Allow update for service_role only" on public.leave_balances for update using (auth.role() = 'service_role');

-- Notifications Policies
create policy "Admins can view their own notifications." on public.notifications for select using (auth.uid() = user_id and public.get_user_role() = 'admin');
create policy "Admins can update their own notifications." on public.notifications for update using (auth.uid() = user_id and public.get_user_role() = 'admin') with check (auth.uid() = user_id);

