-- SECTION 1: TABLE CREATION
-- =============================================
-- Create the 'profiles' table to store user data.
-- This table is linked to the 'auth.users' table.
CREATE TABLE
  public.profiles (
    id UUID NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NULL,
    name VARCHAR NULL,
    avatar_url VARCHAR NULL,
    id_pjlp VARCHAR NULL,
    phone VARCHAR NULL,
    email VARCHAR NULL,
    role VARCHAR DEFAULT 'anggota'::CHARACTER VARYING NULL,
    CONSTRAINT profiles_pkey PRIMARY KEY (id),
    CONSTRAINT profiles_id_pjlp_key UNIQUE (id_pjlp),
    CONSTRAINT profiles_id_fkey FOREIGN KEY (id) REFERENCES auth.users (id) ON DELETE CASCADE
  ) TABLESPACE pg_default;

-- Create the 'leave_requests' table to store leave submissions.
CREATE TABLE
  public.leave_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    title CHARACTER VARYING NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    reason TEXT NULL,
    status CHARACTER VARYING NOT NULL DEFAULT 'Menunggu'::CHARACTER VARYING,
    user_id UUID NOT NULL,
    duration INTEGER NOT NULL,
    attachment_url CHARACTER VARYING NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    is_read_by_user BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT leave_requests_pkey PRIMARY KEY (id),
    CONSTRAINT leave_requests_user_id_fkey FOREIGN KEY (user_id) REFERENCES public.profiles (id) ON DELETE CASCADE
  ) TABLESPACE pg_default;

-- Create the 'leave_balances' table to track annual leave for each user.
CREATE TABLE
  public.leave_balances (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    user_id UUID NOT NULL,
    year INTEGER NOT NULL,
    total_days INTEGER NOT NULL DEFAULT 12,
    used_days INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT leave_balances_pkey PRIMARY KEY (id),
    CONSTRAINT leave_balances_user_id_year_key UNIQUE (user_id, year),
    CONSTRAINT leave_balances_user_id_fkey FOREIGN KEY (user_id) REFERENCES public.profiles (id) ON DELETE CASCADE
  ) TABLESPACE pg_default;

-- Create the 'notifications' table to store notifications for admins.
CREATE TABLE
  public.notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    message TEXT NOT NULL,
    user_id UUID NOT NULL,
    leave_request_id BIGINT NOT NULL,
    is_read BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT notifications_pkey PRIMARY KEY (id),
    CONSTRAINT notifications_leave_request_id_fkey FOREIGN KEY (leave_request_id) REFERENCES public.leave_requests (id) ON DELETE CASCADE,
    CONSTRAINT notifications_user_id_fkey FOREIGN KEY (user_id) REFERENCES public.profiles (id) ON DELETE CASCADE
  ) TABLESPACE pg_default;


-- =============================================
-- SECTION 2: FUNCTION CREATION
-- =============================================

-- Function to get the role of the currently authenticated user.
CREATE OR REPLACE FUNCTION public.get_user_role()
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
  RETURN (
    SELECT role FROM public.profiles WHERE id = auth.uid()
  );
END;
$$;


-- Function to create a profile for a new user.
-- This is triggered by the 'on_auth_user_created' trigger.
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  INSERT INTO public.profiles (id, name, email, id_pjlp, phone, avatar_url)
  VALUES (
    new.id,
    new.raw_user_meta_data->>'name',
    new.email,
    new.raw_user_meta_data->>'id_pjlp',
    new.raw_user_meta_data->>'phone',
    new.raw_user_meta_data->>'avatar_url'
  );
  RETURN new;
END;
$$;

-- Function to create an initial leave balance for a new user.
-- This is triggered by the 'on_profile_created' trigger.
CREATE OR REPLACE FUNCTION public.on_new_user_create_leave_balance()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  current_year integer;
BEGIN
  -- Get the current year
  current_year := EXTRACT(YEAR FROM NOW());

  -- Insert a new leave balance for the current year
  INSERT INTO public.leave_balances (user_id, year, total_days, used_days)
  VALUES (new.id, current_year, 12, 0);

  RETURN new;
END;
$$;


-- Function to create notifications for all admins when a new leave request is submitted.
-- This is triggered by the 'on_leave_request_created' trigger.
CREATE OR REPLACE FUNCTION public.create_admin_notification_for_new_leave()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    admin_record RECORD;
    requesting_user_name TEXT;
BEGIN
    -- Get the name of the user who submitted the request
    SELECT name INTO requesting_user_name FROM public.profiles WHERE id = NEW.user_id;

    -- If the name is null, use a default value
    IF requesting_user_name IS NULL THEN
        requesting_user_name := 'Seorang anggota';
    END IF;

    -- Loop through all admin users and create a notification for each
    FOR admin_record IN SELECT id FROM public.profiles WHERE role = 'admin' LOOP
        INSERT INTO public.notifications (user_id, leave_request_id, message)
        VALUES (admin_record.id, NEW.id, requesting_user_name || ' telah mengajukan cuti baru: "' || NEW.title || '".');
    END LOOP;

    RETURN NEW;
END;
$$;

-- Function to handle the creation of new leave balances at the start of a new year.
-- This function is intended to be run by a cron job.
CREATE OR REPLACE FUNCTION public.handle_new_year_leave_balances()
RETURNS void
LANGUAGE plpgsql
AS $$
DECLARE
  user_record RECORD;
  current_year INTEGER;
BEGIN
  current_year := EXTRACT(YEAR FROM now());

  FOR user_record IN SELECT id FROM public.profiles WHERE role = 'anggota' LOOP
    -- Check if a balance for the current year already exists
    IF NOT EXISTS (
      SELECT 1
      FROM public.leave_balances
      WHERE user_id = user_record.id AND year = current_year
    ) THEN
      -- If not, insert a new balance for the new year
      INSERT INTO public.leave_balances (user_id, year, total_days, used_days)
      VALUES (user_record.id, current_year, 12, 0);
    END IF;
  END LOOP;
END;
$$;


-- =============================================
-- SECTION 3: TRIGGER CREATION
-- =============================================

-- Trigger to execute 'handle_new_user' after a new user is created in auth.users.
CREATE TRIGGER on_auth_user_created
AFTER INSERT ON auth.users
FOR EACH ROW
EXECUTE FUNCTION public.handle_new_user();

-- Trigger to execute 'on_new_user_create_leave_balance' after a new profile is created.
CREATE TRIGGER on_profile_created
AFTER INSERT ON public.profiles
FOR EACH ROW
EXECUTE FUNCTION public.on_new_user_create_leave_balance();

-- Trigger to execute 'create_admin_notification_for_new_leave' after a new leave request is inserted.
CREATE TRIGGER on_leave_request_created
AFTER INSERT ON public.leave_requests
FOR EACH ROW
EXECUTE FUNCTION public.create_admin_notification_for_new_leave();


-- =============================================
-- SECTION 4: PERMISSIONS & ROW-LEVEL SECURITY
-- =============================================

-- Enable RLS for all tables
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.leave_requests ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.leave_balances ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.notifications ENABLE ROW LEVEL SECURITY;

-- Policies for 'profiles' table
DROP POLICY IF EXISTS "Public profiles are viewable by everyone." ON public.profiles;
CREATE POLICY "Public profiles are viewable by everyone." ON public.profiles FOR
SELECT USING (TRUE);

DROP POLICY IF EXISTS "Users can insert their own profile." ON public.profiles;
CREATE POLICY "Users can insert their own profile." ON public.profiles FOR INSERT
WITH
  CHECK (auth.uid() = id);

DROP POLICY IF EXISTS "Users can update their own profile." ON public.profiles;
CREATE POLICY "Users can update their own profile." ON public.profiles FOR
UPDATE USING (auth.uid() = id) WITH CHECK (auth.uid() = id);

DROP POLICY IF EXISTS "Admins can do anything." ON public.profiles;
CREATE POLICY "Admins can do anything." ON public.profiles FOR ALL USING (get_user_role() = 'admin') WITH CHECK (get_user_role() = 'admin');

-- Policies for 'leave_requests' table
DROP POLICY IF EXISTS "Users can view their own leave requests." ON public.leave_requests;
CREATE POLICY "Users can view their own leave requests." ON public.leave_requests FOR
SELECT USING (auth.uid() = user_id);

DROP POLICY IF EXISTS "Users can insert their own leave requests." ON public.leave_requests;
CREATE POLICY "Users can insert their own leave requests." ON public.leave_requests FOR INSERT
WITH
  CHECK (auth.uid() = user_id);

DROP POLICY IF EXISTS "Admins can view and manage all leave requests." ON public.leave_requests;
CREATE POLICY "Admins can view and manage all leave requests." ON public.leave_requests FOR ALL USING (get_user_role() = 'admin') WITH CHECK (get_user_role() = 'admin');

-- Policies for 'leave_balances' table
DROP POLICY IF EXISTS "Users can view their own leave balances." ON public.leave_balances;
CREATE POLICY "Users can view their own leave balances." ON public.leave_balances FOR
SELECT USING (auth.uid() = user_id);

DROP POLICY IF EXISTS "Admins can view and manage all leave balances." ON public.leave_balances;
CREATE POLICY "Admins can view and manage all leave balances." ON public.leave_balances FOR ALL USING (get_user_role() = 'admin') WITH CHECK (get_user_role() = 'admin');

-- Policies for 'notifications' table
DROP POLICY IF EXISTS "Users (admins) can see their own notifications" ON public.notifications;
CREATE POLICY "Users (admins) can see their own notifications" ON public.notifications FOR
SELECT USING (auth.uid() = user_id);

DROP POLICY IF EXISTS "Users (admins) can update their own notifications" ON public.notifications;
CREATE POLICY "Users (admins) can update their own notifications" ON public.notifications FOR
UPDATE USING (auth.uid() = user_id);

-- Permissions for Supabase Storage
-- These are standard permissions for a public bucket where users can upload.
CREATE POLICY "Anyone can see attachments" ON storage.objects FOR
SELECT USING ( bucket_id = 'lampiran-cuti' );

CREATE POLICY "Authenticated users can upload attachments" ON storage.objects FOR INSERT TO authenticated
WITH
  CHECK (bucket_id = 'lampiran-cuti');
  
CREATE POLICY "Authenticated users can update their own attachments" ON storage.objects FOR
UPDATE TO authenticated USING (auth.uid() :: TEXT = owner_id);

CREATE POLICY "Authenticated users can delete their own attachments" ON storage.objects FOR DELETE TO authenticated USING (auth.uid() :: TEXT = owner_id);

