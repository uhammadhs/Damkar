-- -----------------------------------------------------------------------------------------------
-- 1. TABEL PENGGUNA & PROFIL
-- Tabel ini menyimpan data tambahan untuk pengguna, yang tidak ada di tabel `auth.users` bawaan Supabase.
-- -----------------------------------------------------------------------------------------------
CREATE TABLE
  public.profiles (
    id UUID NOT NULL REFERENCES auth.users ON DELETE CASCADE,
    name TEXT,
    id_pjlp TEXT UNIQUE,
    phone TEXT,
    email TEXT,
    role TEXT DEFAULT 'anggota',
    avatar_url TEXT,
    updated_at TIMESTAMPTZ,
    PRIMARY KEY (id)
  );

-- Function untuk menyalin data dari `auth.users` ke `public.profiles` saat ada pengguna baru.
CREATE OR REPLACE FUNCTION public.handle_new_user () RETURNS TRIGGER AS $$
BEGIN
  INSERT INTO public.profiles (id, name, id_pjlp, phone, email, role, avatar_url, updated_at)
  VALUES (
    NEW.id,
    NEW.raw_user_meta_data ->> 'name',
    NEW.raw_user_meta_data ->> 'id_pjlp',
    NEW.raw_user_meta_data ->> 'phone',
    NEW.email,
    'anggota',
    NEW.raw_user_meta_data ->> 'avatar_url',
    NOW()
  );
  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Trigger yang akan menjalankan function `handle_new_user` setelah ada user baru di `auth.users`.
CREATE TRIGGER on_auth_user_created
AFTER INSERT ON auth.users FOR EACH ROW
EXECUTE PROCEDURE public.handle_new_user ();

-- Function untuk mengambil role pengguna saat ini.
CREATE OR REPLACE FUNCTION public.get_user_role () RETURNS TEXT AS $$
BEGIN
  RETURN (
    SELECT role FROM public.profiles WHERE id = auth.uid()
  );
END;
$$ LANGUAGE plpgsql;

-- -----------------------------------------------------------------------------------------------
-- 2. TABEL PENGAJUAN CUTI (leave_requests)
-- Tabel ini menyimpan semua data pengajuan cuti dari para pengguna.
-- -----------------------------------------------------------------------------------------------
CREATE TABLE
  public.leave_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id UUID NOT NULL REFERENCES public.profiles ON DELETE CASCADE,
    title TEXT NOT NULL,
    reason TEXT,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    duration INT NOT NULL,
    status TEXT NOT NULL DEFAULT 'Menunggu',
    attachment_url TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    is_read_by_user BOOLEAN DEFAULT TRUE,
    PRIMARY KEY (id)
  );

-- Function untuk memperbarui kolom `updated_at` secara otomatis.
CREATE OR REPLACE FUNCTION public.update_updated_at_column () RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- Trigger yang akan menjalankan function `update_updated_at_column`.
CREATE TRIGGER handle_leave_requests_update
BEFORE UPDATE ON public.leave_requests FOR EACH ROW
EXECUTE PROCEDURE public.update_updated_at_column ();

-- -----------------------------------------------------------------------------------------------
-- 3. TABEL SALDO CUTI (leave_balances)
-- Tabel ini menyimpan informasi jatah cuti tahunan setiap pengguna.
-- -----------------------------------------------------------------------------------------------
CREATE TABLE
  public.leave_balances (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id UUID NOT NULL REFERENCES public.profiles ON DELETE CASCADE,
    year INT NOT NULL,
    total_days INT NOT NULL DEFAULT 12,
    used_days INT NOT NULL DEFAULT 0,
    UNIQUE (user_id, year),
    PRIMARY KEY (id)
  );

-- Function untuk membuat entri saldo cuti baru saat pengguna baru ditambahkan.
CREATE OR REPLACE FUNCTION public.create_initial_leave_balance() RETURNS TRIGGER AS $$
BEGIN
  INSERT INTO public.leave_balances (user_id, year, total_days, used_days)
  VALUES (NEW.id, EXTRACT(YEAR FROM NOW())::integer, 12, 0);
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- Trigger yang akan menjalankan function `create_initial_leave_balance` setelah profil baru dibuat.
CREATE TRIGGER on_profile_created
AFTER INSERT ON public.profiles FOR EACH ROW
EXECUTE PROCEDURE public.create_initial_leave_balance();

-- -----------------------------------------------------------------------------------------------
-- 4. TABEL NOTIFIKASI (notifications)
-- Tabel ini menyimpan notifikasi untuk admin saat ada pengajuan cuti baru.
-- -----------------------------------------------------------------------------------------------
CREATE TABLE
  public.notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id UUID NOT NULL REFERENCES public.profiles ON DELETE CASCADE, -- ID admin yang akan menerima notifikasi
    leave_request_id BIGINT NOT NULL REFERENCES public.leave_requests ON DELETE CASCADE,
    message TEXT NOT NULL,
    is_read BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (id)
  );

-- Function untuk membuat notifikasi kepada semua admin saat ada pengajuan cuti baru.
CREATE OR REPLACE FUNCTION public.create_admin_notification_for_new_leave() RETURNS TRIGGER AS $$
DECLARE
  admin_record RECORD;
  user_name TEXT;
BEGIN
  -- Ambil nama pemohon dari tabel profiles
  SELECT name INTO user_name FROM public.profiles WHERE id = NEW.user_id;

  -- Loop melalui semua user dengan role 'admin'
  FOR admin_record IN SELECT id FROM public.profiles WHERE role = 'admin' LOOP
    INSERT INTO public.notifications (user_id, leave_request_id, message, is_read)
    VALUES (admin_record.id, NEW.id, user_name || ' mengajukan cuti baru: ' || NEW.title, FALSE);
  END LOOP;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- Trigger yang akan menjalankan function `create_admin_notification_for_new_leave` setelah ada pengajuan cuti baru.
CREATE TRIGGER on_new_leave_request
AFTER INSERT ON public.leave_requests FOR EACH ROW
EXECUTE PROCEDURE public.create_admin_notification_for_new_leave();


