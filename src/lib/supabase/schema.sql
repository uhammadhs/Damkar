-- ----------------------------
-- 1. Enable RLS
-- ----------------------------
alter table profiles enable row level security;
alter table leave_requests enable row level security;
alter table leave_balances enable row level security;
alter table notifications enable row level security;

-- ----------------------------
-- 2. Create Tables
-- ----------------------------

-- Table: profiles
-- Stores user profile information, extending the auth.users table.
create table public.profiles (
    id uuid not null primary key references auth.users on delete cascade,
    name character varying,
    id_pjlp character varying unique,
    phone character varying,
    email character varying,
    avatar_url character varying,
    role character varying default 'anggota',
    updated_at timestamp with time zone
);
comment on table public.profiles is 'Stores user profile information, extending the auth.users table.';

-- Table: leave_requests
-- Stores all leave requests submitted by users.
create table public.leave_requests (
    id bigint generated by default as identity primary key,
    user_id uuid not null references public.profiles on delete cascade,
    title character varying not null,
    reason text,
    start_date date not null,
    end_date date not null,
    duration integer not null,
    status character varying not null default 'Menunggu',
    attachment_url text,
    is_read_by_user boolean not null default false,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now()
);
comment on table public.leave_requests is 'Stores all leave requests submitted by users.';

-- Table: leave_balances
-- Tracks the annual leave balance for each user.
create table public.leave_balances (
    id bigint generated by default as identity primary key,
    user_id uuid not null references public.profiles on delete cascade,
    year integer not null,
    total_days integer not null default 12,
    used_days integer not null default 0,
    unique (user_id, year)
);
comment on table public.leave_balances is 'Tracks the annual leave balance for each user.';

-- Table: notifications
-- Stores notifications for admins regarding new leave requests.
create table public.notifications (
    id bigint generated by default as identity primary key,
    user_id uuid not null references public.profiles on delete cascade, -- The admin user who receives the notification
    leave_request_id bigint not null references public.leave_requests on delete cascade,
    message text not null,
    is_read boolean not null default false,
    created_at timestamp with time zone not null default now()
);
comment on table public.notifications is 'Stores notifications for admins regarding new leave requests.';


-- ----------------------------
-- 3. Create Functions
-- ----------------------------

-- Function: handle_new_user
-- Automatically creates a profile entry when a new user signs up in auth.users.
create function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.profiles (id, name, id_pjlp, phone, email, avatar_url, role)
  values (
    new.id,
    new.raw_user_meta_data->>'name',
    new.raw_user_meta_data->>'id_pjlp',
    new.raw_user_meta_data->>'phone',
    new.email,
    new.raw_user_meta_data->>'avatar_url',
    'anggota' -- Default role for new sign-ups
  );
  return new;
end;
$$;
comment on function public.handle_new_user() is 'Creates a profile for a new user.';

-- Function: on_new_user_create_leave_balance
-- Automatically creates an initial leave balance for a new user's profile for the current year.
create function public.on_new_user_create_leave_balance()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  -- Insert a leave balance for the current year
  insert into public.leave_balances (user_id, year, total_days, used_days)
  values (new.id, extract(year from now()), 12, 0);
  return new;
end;
$$;
comment on function public.on_new_user_create_leave_balance() is 'Creates an initial leave balance for a new user.';

-- Function: create_admin_notification_for_new_leave
-- Creates a notification for all 'admin' role users when a new leave request is inserted.
create function public.create_admin_notification_for_new_leave()
returns trigger
language plpgsql
security definer set search_path = public
as $$
declare
  admin_record record;
  applicant_name text;
begin
  -- Get the name of the user who submitted the request
  select name into applicant_name from public.profiles where id = new.user_id;

  -- If the name is null, use a default value
  if applicant_name is null then
    applicant_name := 'Seorang anggota';
  end if;

  -- Loop through all admins and create a notification for each one
  for admin_record in select id from public.profiles where role = 'admin'
  loop
    insert into public.notifications (user_id, leave_request_id, message)
    values (admin_record.id, new.id, applicant_name || ' telah mengajukan cuti baru: "' || new.title || '".');
  end loop;

  return new;
end;
$$;
comment on function public.create_admin_notification_for_new_leave() is 'Creates notifications for all admins on a new leave request.';

-- Function: get_user_role
-- A security barrier function to get the role of the currently authenticated user.
create function public.get_user_role()
returns text
language plpgsql
security definer set search_path = public
as $$
declare
  user_role text;
begin
  select role into user_role from public.profiles where id = auth.uid();
  return user_role;
end;
$$;
comment on function public.get_user_role() is 'Returns the role of the currently authenticated user.';

-- Function: handle_new_year_leave_balances
-- This function is intended to be run as a cron job at the beginning of each year.
-- It creates a new leave balance entry for the new year for all active 'anggota' users.
create function public.handle_new_year_leave_balances()
returns void
language plpgsql
as $$
declare
  user_record record;
  current_year integer;
begin
  current_year := extract(year from now());

  -- Loop through all users with the 'anggota' role
  for user_record in select id from public.profiles where role = 'anggota'
  loop
    -- Check if a balance for the current year already exists for the user
    if not exists (
      select 1
      from public.leave_balances
      where user_id = user_record.id and year = current_year
    ) then
      -- If it doesn't exist, insert a new balance for the new year
      insert into public.leave_balances (user_id, year, total_days, used_days)
      values (user_record.id, current_year, 12, 0);
    end if;
  end loop;
end;
$$;
comment on function public.handle_new_year_leave_balances() is 'Scheduled function to create new yearly leave balances for all members.';


