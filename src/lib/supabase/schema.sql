-- Function to get user's role from their profile.
create or replace function public.get_user_role()
returns text
language sql
security definer
set search_path = public
stable
as $$
    select role from public.profiles where id = auth.uid()
$$;
comment on function public.get_user_role() is 'Get the role of the currently authenticated user.';

-- Function to automatically create a profile for a new user.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  current_year integer;
begin
  -- Create a profile
  insert into public.profiles (id, name, id_pjlp, phone, email)
  values (
    new.id,
    new.raw_user_meta_data->>'name',
    new.raw_user_meta_data->>'id_pjlp',
    new.raw_user_meta_data->>'phone',
    new.email
  );

  -- Create an initial leave balance for the current year
  current_year := extract(year from now());
  insert into public.leave_balances (user_id, year, total_days, used_days)
  values (new.id, current_year, 12, 0);
  
  return new;
end;
$$;
comment on function public.handle_new_user() is 'Trigger function to create a profile and initial leave balance for a new user.';

-- Function to create leave balances for a new year for all active 'anggota'.
create or replace function public.handle_new_year_leave_balances()
returns void
language plpgsql
as $$
declare
    user_record record;
    new_year integer;
begin
    new_year := extract(year from now());
    for user_record in select id from public.profiles where role = 'anggota' loop
        -- Insert a new leave balance entry only if it doesn't already exist
        insert into public.leave_balances (user_id, year, total_days, used_days)
        values (user_record.id, new_year, 12, 0)
        on conflict (user_id, year) do nothing;
    end loop;
end;
$$;
comment on function public.handle_new_year_leave_balances() is 'Creates leave balance entries for the new year for all members.';

-- Function to create a notification for admins when a new leave request is submitted.
create or replace function public.create_admin_notification_for_new_leave()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
    admin_record record;
    applicant_name text;
begin
    -- Get the applicant's name
    select name into applicant_name from public.profiles where id = new.user_id;

    -- Create a notification for each admin
    for admin_record in select id from public.profiles where role = 'admin' loop
        insert into public.notifications (user_id, leave_request_id, message)
        values (admin_record.id, new.id, applicant_name || ' telah mengajukan cuti baru: "' || new.title || '".');
    end loop;
    return new;
end;
$$;
comment on function public.create_admin_notification_for_new_leave() is 'Trigger function to notify all admins about a new leave request.';

-- RPC function for logging in with ID PJLP and password.
create or replace function public.login_with_id_pjlp(p_id_pjlp text, p_password text)
returns json
language plpgsql
security definer
set search_path = public
as $$
declare
    user_email text;
    user_id uuid;
    user_role text;
    auth_uid uuid;
    session json;
begin
    -- 1. Find user email, id, and role from profiles table based on id_pjlp
    select email, id, role into user_email, user_id, user_role
    from public.profiles
    where profiles.id_pjlp = p_id_pjlp;

    -- 2. If no user found, return error
    if user_email is null then
        return json_build_object('error', 'Kombinasi ID PJLP dan Password tidak valid.');
    end if;

    -- 3. Use the service role to sign in the user by email and password
    select auth.sign_in_with_password(user_email, p_password) into session;
    
    -- 4. Check for authentication errors within the returned session object
    if session->>'error' is not null then
        -- Even if password is wrong, give a generic error for security
        return json_build_object('error', 'Kombinasi ID PJLP dan Password tidak valid.');
    end if;

    -- 5. If login is successful, return user info
    return json_build_object(
        'success', true,
        'user_id', user_id,
        'email', user_email,
        'role', user_role
    );
exception
    when others then
        return json_build_object('error', 'Terjadi kesalahan internal pada server.');
end;
$$;
comment on function public.login_with_id_pjlp(text, text) is 'Logs a user in using their ID PJLP and password, returning a session and role.';

