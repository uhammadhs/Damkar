
-- ### SIAP CUTI SCHEMA ###
-- This schema is designed for a leave management application.
-- It includes tables for user profiles, leave requests, leave balances,
-- and notifications. It also sets up triggers for automation and
-- Row-Level Security (RLS) for data protection.

-- ----------------------------------------------------------------
-- 1. EXTENSIONS
-- ----------------------------------------------------------------
-- (No extensions needed for this schema, Supabase handles them)

-- ----------------------------------------------------------------
-- 2. TABLES
-- ----------------------------------------------------------------

-- Table: profiles
-- Stores user profile information, extending the auth.users table.
CREATE TABLE
  public.profiles (
    id uuid NOT NULL PRIMARY KEY REFERENCES auth.users (id) ON DELETE CASCADE,
    updated_at timestamp with time zone,
    name character varying,
    avatar_url character varying,
    id_pjlp character varying UNIQUE,
    phone character varying,
    email character varying,
    role character varying DEFAULT 'anggota'::character varying
  );

ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
COMMENT ON TABLE public.profiles IS 'Stores public profile information for each user.';

-- Table: leave_requests
-- Stores all leave requests submitted by users.
CREATE TABLE
  public.leave_requests (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    user_id uuid NOT NULL REFERENCES public.profiles (id) ON DELETE CASCADE,
    title character varying NOT NULL,
    reason text,
    start_date date NOT NULL,
    end_date date NOT NULL,
    duration integer NOT NULL,
    status character varying NOT NULL DEFAULT 'Menunggu'::character varying,
    attachment_url text,
    updated_at timestamp with time zone NOT NULL DEFAULT now(),
    is_read_by_user boolean NOT NULL DEFAULT false
  );

ALTER TABLE public.leave_requests ENABLE ROW LEVEL SECURITY;
COMMENT ON TABLE public.leave_requests IS 'Stores leave requests from users.';
CREATE INDEX leave_requests_user_id_idx ON public.leave_requests (user_id);
CREATE INDEX leave_requests_status_idx ON public.leave_requests (status);


-- Table: leave_balances
-- Stores the annual leave balance for each user.
CREATE TABLE
  public.leave_balances (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid NOT NULL REFERENCES public.profiles (id) ON DELETE CASCADE,
    year integer NOT NULL,
    total_days integer NOT NULL DEFAULT 12,
    used_days integer NOT NULL DEFAULT 0,
    CONSTRAINT leave_balances_user_id_year_key UNIQUE (user_id, year)
  );

ALTER TABLE public.leave_balances ENABLE ROW LEVEL SECURITY;
COMMENT ON TABLE public.leave_balances IS 'Stores annual leave balance for each user.';
CREATE INDEX leave_balances_user_id_year_idx ON public.leave_balances (user_id, year);


-- Table: notifications
-- Stores notifications for admins about new leave requests.
CREATE TABLE
  public.notifications (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    user_id uuid NOT NULL REFERENCES public.profiles (id) ON DELETE CASCADE,
    leave_request_id bigint NOT NULL REFERENCES public.leave_requests (id) ON DELETE CASCADE,
    message text NOT NULL,
    is_read boolean NOT NULL DEFAULT false
  );

ALTER TABLE public.notifications ENABLE ROW LEVEL SECURITY;
COMMENT ON TABLE public.notifications IS 'Notifications for admins about new leave requests.';

-- ----------------------------------------------------------------
-- 3. FUNCTIONS & TRIGGERS
-- ----------------------------------------------------------------

-- Function: handle_new_user
-- Copies data from auth.users to public.profiles
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
  INSERT INTO public.profiles (id, name, email, id_pjlp, phone, role)
  VALUES (
    new.id,
    new.raw_user_meta_data->>'name',
    new.email,
    new.raw_user_meta_data->>'id_pjlp',
    new.raw_user_meta_data->>'phone',
    'anggota'
  );
  RETURN new;
END;
$$;

-- Trigger: on_auth_user_created
-- Fires the handle_new_user function after a new user is created
CREATE TRIGGER on_auth_user_created
AFTER INSERT ON auth.users
FOR EACH ROW
EXECUTE FUNCTION public.handle_new_user();


-- Function: on_new_user_create_leave_balance
-- Automatically creates an initial leave balance for a new user.
CREATE OR REPLACE FUNCTION public.on_new_user_create_leave_balance()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
  INSERT INTO public.leave_balances(user_id, year, total_days, used_days)
  VALUES(new.id, date_part('year', now()), 12, 0);
  RETURN new;
END;
$$;

-- Trigger: on_profile_created
-- Fires after a new profile is inserted.
CREATE TRIGGER on_profile_created
AFTER INSERT ON public.profiles
FOR EACH ROW
EXECUTE FUNCTION public.on_new_user_create_leave_balance();


-- Function: create_admin_notification_for_new_leave
-- Creates a notification for all admin users when a new leave request is submitted.
CREATE OR REPLACE FUNCTION public.create_admin_notification_for_new_leave()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  admin_record RECORD;
  applicant_name TEXT;
BEGIN
  -- Get the name of the applicant
  SELECT name INTO applicant_name FROM public.profiles WHERE id = NEW.user_id;

  -- Loop through all admin users and create a notification for each
  FOR admin_record IN SELECT id FROM public.profiles WHERE role = 'admin'
  LOOP
    INSERT INTO public.notifications (user_id, leave_request_id, message)
    VALUES (admin_record.id, NEW.id, applicant_name || ' telah mengajukan cuti baru: "' || NEW.title || '"');
  END LOOP;
  RETURN NEW;
END;
$$;

-- Trigger: on_leave_request_created
-- Fires after a new leave request is created
CREATE TRIGGER on_leave_request_created
AFTER INSERT ON public.leave_requests
FOR EACH ROW
EXECUTE FUNCTION public.create_admin_notification_for_new_leave();


-- Function: get_user_role()
-- A helper function to get the role of the currently authenticated user.
CREATE OR REPLACE FUNCTION public.get_user_role()
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  user_role text;
BEGIN
  SELECT role INTO user_role
  FROM public.profiles
  WHERE id = auth.uid();
  RETURN user_role;
END;
$$;

-- ----------------------------------------------------------------
-- 4. ROW-LEVEL SECURITY (RLS) POLICIES
-- ----------------------------------------------------------------

-- Policies for profiles table
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Public profiles are viewable by everyone." ON public.profiles;
CREATE POLICY "Public profiles are viewable by everyone." ON public.profiles FOR SELECT USING (true);
DROP POLICY IF EXISTS "Users can insert their own profile." ON public.profiles;
CREATE POLICY "Users can insert their own profile." ON public.profiles FOR INSERT WITH CHECK (auth.uid() = id);
DROP POLICY IF EXISTS "Users can update their own profile." ON public.profiles;
CREATE POLICY "Users can update their own profile." ON public.profiles FOR UPDATE USING (auth.uid() = id);
DROP POLICY IF EXISTS "Admins can manage all profiles." ON public.profiles;
CREATE POLICY "Admins can manage all profiles." ON public.profiles FOR ALL USING (get_user_role() = 'admin');

-- Policies for leave_requests table
ALTER TABLE public.leave_requests ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Users can view their own leave requests." ON public.leave_requests;
CREATE POLICY "Users can view their own leave requests." ON public.leave_requests FOR SELECT USING (auth.uid() = user_id);
DROP POLICY IF EXISTS "Users can create leave requests." ON public.leave_requests;
CREATE POLICY "Users can create leave requests." ON public.leave_requests FOR INSERT WITH CHECK (auth.uid() = user_id);
DROP POLICY IF EXISTS "Users can update their own unapproved requests." ON public.leave_requests;
CREATE POLICY "Users can update their own unapproved requests." ON public.leave_requests FOR UPDATE USING (auth.uid() = user_id AND status = 'Menunggu');
DROP POLICY IF EXISTS "Admins can manage all leave requests." ON public.leave_requests;
CREATE POLICY "Admins can manage all leave requests." ON public.leave_requests FOR ALL USING (get_user_role() = 'admin');


-- Policies for leave_balances table
ALTER TABLE public.leave_balances ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Users can view their own leave balances." ON public.leave_balances;
CREATE POLICY "Users can view their own leave balances." ON public.leave_balances FOR SELECT USING (auth.uid() = user_id);
DROP POLICY IF EXISTS "Admins can manage all leave balances." ON public.leave_balances;
CREATE POLICY "Admins can manage all leave balances." ON public.leave_balances FOR ALL USING (get_user_role() = 'admin');

-- Policies for notifications table
ALTER TABLE public.notifications ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Admins can view their own notifications." ON public.notifications;
CREATE POLICY "Admins can view their own notifications." ON public.notifications FOR SELECT USING (get_user_role() = 'admin' AND auth.uid() = user_id);
DROP POLICY IF EXISTS "Admins can update their own notifications." ON public.notifications;
CREATE POLICY "Admins can update their own notifications." ON public.notifications FOR UPDATE USING (get_user_role() = 'admin' AND auth.uid() = user_id);

-- ----------------------------------------------------------------
-- 5. INITIAL GRANTS
-- ----------------------------------------------------------------
-- Granting usage on the public schema to anon and authenticated roles.
grant usage on schema public to postgres, anon, authenticated, service_role;
-- Granting all privileges on all tables in the public schema to the service_role.
-- This allows our server-side code (using the service_role key) to bypass RLS.
grant all on all tables in schema public to postgres, service_role;
grant all on all functions in schema public to postgres, service_role;
grant all on all sequences in schema public to postgres, service_role;
-- Granting specific privileges to anon and authenticated roles.
-- These roles are subject to RLS policies.
grant execute on function public.get_user_role() to authenticated;
alter default privileges in schema public grant all on tables to postgres, service_role;
alter default privileges in schema public grant all on functions to postgres, service_role;
alter default privileges in schema public grant all on sequences to postgres, service_role;

-- Allow authenticated users to perform specific actions on tables
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.profiles TO authenticated;
GRANT SELECT, INSERT, UPDATE ON TABLE public.leave_requests TO authenticated;
GRANT SELECT ON TABLE public.leave_balances TO authenticated;
GRANT SELECT, UPDATE ON TABLE public.notifications TO authenticated;


