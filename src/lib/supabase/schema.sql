-- 2. PEMBUATAN TABEL
-- Tabel untuk menyimpan profil pengguna, diperluas dari auth.users
CREATE TABLE public.profiles (
    id uuid NOT NULL PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    updated_at timestamp with time zone,
    name text,
    id_pjlp text UNIQUE,
    phone text,
    email text,
    avatar_url text,
    role text DEFAULT 'anggota'::text
);
COMMENT ON TABLE public.profiles IS 'Tabel untuk data profil publik pengguna.';

-- Tabel untuk menyimpan pengajuan cuti
CREATE TABLE public.leave_requests (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    updated_at timestamp with time zone DEFAULT now() NOT NULL,
    start_date date NOT NULL,
    end_date date NOT NULL,
    duration integer NOT NULL,
    title text NOT NULL,
    reason text,
    status text DEFAULT 'Menunggu'::text NOT NULL,
    attachment_url text,
    is_read_by_user boolean DEFAULT false NOT NULL
);
COMMENT ON TABLE public.leave_requests IS 'Menyimpan semua data pengajuan cuti dari anggota.';

-- Tabel untuk menyimpan saldo cuti tahunan
CREATE TABLE public.leave_balances (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    year integer NOT NULL,
    total_days integer DEFAULT 12 NOT NULL,
    used_days integer DEFAULT 0 NOT NULL,
    UNIQUE (user_id, year)
);
COMMENT ON TABLE public.leave_balances IS 'Menyimpan saldo cuti tahunan untuk setiap pengguna.';

-- Tabel untuk notifikasi admin
CREATE TABLE public.notifications (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    leave_request_id bigint NOT NULL REFERENCES public.leave_requests(id) ON DELETE CASCADE,
    message text NOT NULL,
    is_read boolean DEFAULT false NOT NULL,
    created_at timestamp with time zone DEFAULT now() NOT NULL
);
COMMENT ON TABLE public.notifications IS 'Notifikasi untuk admin tentang pengajuan cuti baru.';


-- 3. FUNGSI-FUNGSI HELPER & LOGIKA BISNIS
-- Fungsi untuk mendapatkan peran (role) pengguna yang sedang login
CREATE OR REPLACE FUNCTION public.get_user_role()
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
  IF auth.uid() IS NULL THEN
    RETURN NULL;
  ELSE
    RETURN (SELECT role FROM public.profiles WHERE id = auth.uid());
  END IF;
END;
$$;
COMMENT ON FUNCTION public.get_user_role() IS 'Mengambil peran (admin/anggota) dari pengguna yang sedang terotentikasi.';

-- Fungsi untuk membuat profil baru secara otomatis setelah user mendaftar
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
  INSERT INTO public.profiles (id, name, id_pjlp, phone, email, role)
  VALUES (
    new.id,
    new.raw_user_meta_data->>'name',
    new.raw_user_meta_data->>'id_pjlp',
    new.raw_user_meta_data->>'phone',
    new.email,
    'anggota'
  );
  RETURN new;
END;
$$;
COMMENT ON FUNCTION public.handle_new_user() IS 'Membuat entri di tabel profiles setiap kali user baru terdaftar di auth.users.';

-- Fungsi untuk membuat saldo cuti tahunan jika belum ada
CREATE OR REPLACE FUNCTION public.create_leave_balance_if_not_exists()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    v_year integer;
BEGIN
    v_year := EXTRACT(YEAR FROM NEW.start_date);
    -- Cek jika saldo untuk tahun tersebut sudah ada
    IF NOT EXISTS (
        SELECT 1
        FROM public.leave_balances
        WHERE user_id = NEW.user_id AND year = v_year
    ) THEN
        -- Jika tidak ada, buat saldo baru
        INSERT INTO public.leave_balances (user_id, year, total_days, used_days)
        VALUES (NEW.user_id, v_year, 12, 0);
    END IF;
    RETURN NEW;
END;
$$;
COMMENT ON FUNCTION public.create_leave_balance_if_not_exists() IS 'Secara otomatis membuat saldo cuti tahunan jika belum ada saat pengajuan pertama di tahun tersebut.';


-- Fungsi untuk memperbarui saldo cuti saat status pengajuan diubah
CREATE OR REPLACE FUNCTION public.handle_leave_balance_update()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  leave_year int;
  leave_duration int;
BEGIN
  leave_year := EXTRACT(YEAR FROM NEW.start_date);
  leave_duration := NEW.duration;

  -- Jika status diubah MENJADI 'Disetujui'
  IF NEW.status = 'Disetujui' AND OLD.status != 'Disetujui' THEN
    UPDATE public.leave_balances
    SET used_days = used_days + leave_duration
    WHERE user_id = NEW.user_id AND year = leave_year;
  -- Jika status diubah DARI 'Disetujui' ke status lain (misal: Ditolak)
  ELSIF OLD.status = 'Disetujui' AND NEW.status != 'Disetujui' THEN
    UPDATE public.leave_balances
    SET used_days = used_days - leave_duration
    WHERE user_id = NEW.user_id AND year = leave_year;
  END IF;

  RETURN NEW;
END;
$$;
COMMENT ON FUNCTION public.handle_leave_balance_update() IS 'Memperbarui `used_days` di `leave_balances` saat status pengajuan berubah ke/dari "Disetujui".';

-- Fungsi untuk membuat notifikasi untuk semua admin saat ada pengajuan baru
CREATE OR REPLACE FUNCTION public.create_admin_notification_for_new_leave()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  admin_record record;
  applicant_name text;
BEGIN
  -- Dapatkan nama pemohon
  SELECT name INTO applicant_name FROM public.profiles WHERE id = NEW.user_id;

  -- Loop melalui semua admin dan buat notifikasi untuk masing-masing
  FOR admin_record IN SELECT id FROM public.profiles WHERE role = 'admin' LOOP
    INSERT INTO public.notifications(user_id, leave_request_id, message)
    VALUES(admin_record.id, NEW.id, applicant_name || ' mengajukan cuti baru: ' || NEW.title);
  END LOOP;
  RETURN NEW;
END;
$$;
COMMENT ON FUNCTION public.create_admin_notification_for_new_leave() IS 'Membuat notifikasi untuk semua admin setiap ada pengajuan cuti baru.';


-- 4. TRIGGERS
-- Trigger untuk handle_new_user
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE PROCEDURE public.handle_new_user();

-- Trigger untuk membuat saldo cuti jika belum ada saat pengajuan pertama
CREATE TRIGGER trigger_check_leave_balance_on_insert
    BEFORE INSERT ON public.leave_requests
    FOR EACH ROW
    EXECUTE FUNCTION public.create_leave_balance_if_not_exists();

-- Trigger untuk memperbarui saldo cuti saat status berubah
CREATE TRIGGER on_leave_request_status_change
  AFTER UPDATE OF status ON public.leave_requests
  FOR EACH ROW EXECUTE PROCEDURE public.handle_leave_balance_update();

-- Trigger untuk membuat notifikasi admin saat ada pengajuan baru
CREATE TRIGGER on_leave_request_inserted
  AFTER INSERT ON public.leave_requests
  FOR EACH ROW EXECUTE PROCEDURE public.create_admin_notification_for_new_leave();


