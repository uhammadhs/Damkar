-- ------------------------------------------------------------------------------------------------
-- 1. TABEL UTAMA
-- ------------------------------------------------------------------------------------------------
-- Tabel untuk menyimpan data profil pengguna, diperluas dari auth.users
CREATE TABLE
  public.profiles (
    id UUID NOT NULL PRIMARY KEY REFERENCES auth.users (id) ON DELETE CASCADE,
    name TEXT,
    id_pjlp TEXT UNIQUE,
    phone TEXT,
    email TEXT UNIQUE,
    avatar_url TEXT,
    role TEXT DEFAULT 'anggota',
    updated_at TIMESTAMPTZ
  );

ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;

-- Tabel untuk menyimpan saldo cuti tahunan setiap pengguna
CREATE TABLE
  public.leave_balances (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES public.profiles (id) ON DELETE CASCADE,
    year INT NOT NULL,
    total_days INT NOT NULL DEFAULT 12,
    used_days INT NOT NULL DEFAULT 0,
    UNIQUE (user_id, year)
  );

ALTER TABLE public.leave_balances ENABLE ROW LEVEL SECURITY;

-- Tabel untuk menyimpan riwayat pengajuan cuti
CREATE TABLE
  public.leave_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES public.profiles (id) ON DELETE CASCADE,
    title TEXT NOT NULL,
    reason TEXT,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    duration INT NOT NULL,
    status TEXT NOT NULL DEFAULT 'Menunggu',
    attachment_url TEXT,
    is_read_by_user BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
  );

ALTER TABLE public.leave_requests ENABLE ROW LEVEL SECURITY;

-- Tabel untuk menyimpan notifikasi
CREATE TABLE
  public.notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES public.profiles (id) ON DELETE CASCADE,
    leave_request_id BIGINT NOT NULL REFERENCES public.leave_requests (id) ON DELETE CASCADE,
    message TEXT NOT NULL,
    is_read BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
  );

ALTER TABLE public.notifications ENABLE ROW LEVEL SECURITY;

