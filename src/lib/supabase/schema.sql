-- 1. ========== PENGATURAN TABEL PROFIL PENGGUNA ==========
-- Tabel ini akan menyimpan data publik pengguna, diperluas dari tabel auth.users.
CREATE TABLE public.profiles (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    name TEXT,
    email TEXT UNIQUE,
    id_pjlp TEXT UNIQUE,
    phone TEXT,
    avatar_url TEXT,
    role TEXT DEFAULT 'anggota',
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Kebijakan RLS untuk tabel profiles:
-- 1. Izinkan pengguna untuk melihat semua profil (untuk referensi).
-- 2. Izinkan pengguna untuk memperbarui profil mereka sendiri.
-- 3. Izinkan admin untuk mengelola semua profil.
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Public profiles are viewable by everyone." 
ON public.profiles FOR SELECT USING (true);

CREATE POLICY "Users can update their own profile." 
ON public.profiles FOR UPDATE USING (auth.uid() = id);

CREATE POLICY "Admins can manage all profiles."
ON public.profiles FOR ALL USING ((SELECT get_user_role()) = 'admin');


-- 2. ========== PENGATURAN TABEL PENGAJUAN CUTI ==========
CREATE TABLE public.leave_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    title TEXT NOT NULL,
    reason TEXT,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    duration INT NOT NULL,
    status TEXT NOT NULL DEFAULT 'Menunggu', -- Menunggu, Disetujui, Ditolak
    attachment_url TEXT,
    is_read_by_user BOOLEAN DEFAULT TRUE NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Kebijakan RLS untuk tabel leave_requests:
-- 1. Pengguna bisa melihat dan membuat pengajuan cuti mereka sendiri.
-- 2. Admin bisa mengelola semua pengajuan cuti.
ALTER TABLE public.leave_requests ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Users can manage their own leave requests."
ON public.leave_requests FOR ALL USING (auth.uid() = user_id);

CREATE POLICY "Admins can manage all leave requests."
ON public.leave_requests FOR ALL USING ((SELECT get_user_role()) = 'admin');


-- 3. ========== PENGATURAN TABEL SALDO CUTI ==========
CREATE TABLE public.leave_balances (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    year INT NOT NULL,
    total_days INT NOT NULL DEFAULT 12,
    used_days INT NOT NULL DEFAULT 0,
    UNIQUE (user_id, year) -- Pastikan setiap pengguna hanya punya 1 entri per tahun
);

-- Kebijakan RLS untuk tabel leave_balances:
-- 1. Pengguna bisa melihat saldo cuti mereka sendiri.
-- 2. Admin bisa mengelola semua saldo cuti.
ALTER TABLE public.leave_balances ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Users can view their own leave balance."
ON public.leave_balances FOR SELECT USING (auth.uid() = user_id);

CREATE POLICY "Admins can manage all leave balances."
ON public.leave_balances FOR ALL USING ((SELECT get_user_role()) = 'admin');


-- 4. ========== PENGATURAN TABEL NOTIFIKASI ADMIN ==========
CREATE TABLE public.notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    leave_request_id BIGINT NOT NULL REFERENCES public.leave_requests(id) ON DELETE CASCADE,
    message TEXT NOT NULL,
    is_read BOOLEAN DEFAULT FALSE NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW() NOT NULL
);

-- Kebijakan RLS untuk tabel notifications:
-- 1. Admin bisa melihat dan memperbarui notifikasi mereka sendiri.
ALTER TABLE public.notifications ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Admins can see their own notifications."
ON public.notifications FOR SELECT USING ((SELECT get_user_role()) = 'admin' AND auth.uid() = user_id);

CREATE POLICY "Admins can update their own notifications."
ON public.notifications FOR UPDATE USING ((SELECT get_user_role()) = 'admin' AND auth.uid() = user_id);


-- 5. ========== FUNGSI DAN TRIGGER DATABASE ==========

-- Fungsi untuk mendapatkan peran pengguna saat ini.
-- Berguna untuk kebijakan RLS.
CREATE OR REPLACE FUNCTION public.get_user_role()
RETURNS TEXT
LANGUAGE plpgsql
AS $$
DECLARE
  user_role TEXT;
BEGIN
  SELECT role INTO user_role FROM public.profiles WHERE id = auth.uid();
  RETURN user_role;
END;
$$;


-- Fungsi untuk secara otomatis membuat profil baru saat ada pengguna baru mendaftar.
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER -- Jalankan dengan izin penuh untuk menyisipkan data.
SET search_path = public
AS $$
BEGIN
  INSERT INTO public.profiles (id, name, email, id_pjlp, phone, role)
  VALUES (
    NEW.id,
    NEW.raw_user_meta_data->>'name',
    NEW.email,
    NEW.raw_user_meta_data->>'id_pjlp',
    NEW.raw_user_meta_data->>'phone',
    'anggota' -- Role default
  );
  RETURN NEW;
END;
$$;

-- Trigger yang memanggil handle_new_user() setiap kali ada user baru di auth.users.
CREATE TRIGGER on_auth_user_created
AFTER INSERT ON auth.users
FOR EACH ROW EXECUTE PROCEDURE public.handle_new_user();


-- Fungsi untuk memperbarui saldo cuti saat status pengajuan diubah.
CREATE OR REPLACE FUNCTION public.handle_leave_balance_update()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER -- Jalankan dengan izin penuh untuk mencegah error akses.
AS $$
DECLARE
  leave_year INT;
  default_total_days INT := 12; -- Jatah cuti default
BEGIN
  leave_year := EXTRACT(YEAR FROM NEW.start_date);

  -- Pastikan data saldo cuti untuk pengguna dan tahun tersebut ada.
  -- Jika tidak ada, buat baru. Ini adalah KUNCI untuk mencegah error.
  INSERT INTO public.leave_balances (user_id, year, total_days, used_days)
  VALUES (NEW.user_id, leave_year, default_total_days, 0)
  ON CONFLICT (user_id, year) DO NOTHING;

  -- Jika status diubah menjadi 'Disetujui' dari status lain.
  IF NEW.status = 'Disetujui' AND OLD.status != 'Disetujui' THEN
    UPDATE public.leave_balances
    SET used_days = used_days + NEW.duration
    WHERE user_id = NEW.user_id AND year = leave_year;

  -- Jika persetujuan dibatalkan (dari 'Disetujui' menjadi status lain).
  ELSIF OLD.status = 'Disetujui' AND NEW.status != 'Disetujui' THEN
    UPDATE public.leave_balances
    SET used_days = used_days - NEW.duration
    WHERE user_id = NEW.user_id AND year = leave_year;
  END IF;

  RETURN NEW;
END;
$$;

-- Trigger yang memanggil handle_leave_balance_update() saat status di leave_requests berubah.
CREATE TRIGGER on_leave_request_status_change
AFTER UPDATE ON public.leave_requests
FOR EACH ROW
WHEN (OLD.status IS DISTINCT FROM NEW.status)
EXECUTE FUNCTION public.handle_leave_balance_update();


-- Fungsi untuk membuat notifikasi bagi semua admin saat ada pengajuan cuti baru.
CREATE OR REPLACE FUNCTION public.create_admin_notification_for_new_leave()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER -- Jalankan dengan izin penuh untuk membaca data admin.
AS $$
DECLARE
  admin_record RECORD;
  applicant_name TEXT;
BEGIN
  -- Ambil nama pemohon dari tabel profiles.
  SELECT name INTO applicant_name FROM public.profiles WHERE id = NEW.user_id;
  IF applicant_name IS NULL THEN
    applicant_name := 'Seorang anggota';
  END IF;

  -- Loop melalui semua admin dan buat notifikasi untuk masing-masing.
  FOR admin_record IN SELECT id FROM public.profiles WHERE role = 'admin' LOOP
    INSERT INTO public.notifications (user_id, leave_request_id, message)
    VALUES (admin_record.id, NEW.id, applicant_name || ' mengajukan cuti baru: "' || NEW.title || '"');
  END LOOP;
  RETURN NEW;
END;
$$;

-- Trigger yang memanggil create_admin_notification_for_new_leave() saat ada pengajuan baru.
CREATE TRIGGER on_new_leave_request_insert
AFTER INSERT ON public.leave_requests
FOR EACH ROW
EXECUTE FUNCTION public.create_admin_notification_for_new_leave();


