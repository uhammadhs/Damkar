-- 1. Hapus tabel lama jika ada untuk memastikan instalasi yang bersih
DROP TABLE IF EXISTS public.notifications;
DROP TABLE IF EXISTS public.leave_balances;
DROP TABLE IF EXISTS public.leave_requests;
DROP TABLE IF EXISTS public.profiles;


-- 2. Setup Tables
-- Tabel untuk menyimpan data profil pengguna, diperluas dari auth.users
CREATE TABLE public.profiles (
  id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  name TEXT,
  id_pjlp TEXT UNIQUE,
  phone TEXT,
  email TEXT,
  avatar_url TEXT,
  role TEXT DEFAULT 'anggota',
  updated_at TIMESTAMPTZ
);

-- Tabel untuk menyimpan semua pengajuan cuti
CREATE TABLE public.leave_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  title TEXT NOT NULL,
  reason TEXT,
  start_date TIMESTAMPTZ NOT NULL,
  end_date TIMESTAMPTZ NOT NULL,
  duration INT NOT NULL,
  status TEXT NOT NULL DEFAULT 'Menunggu', -- Menunggu, Disetujui, Ditolak
  attachment_url TEXT,
  is_read_by_user BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Tabel untuk melacak saldo cuti tahunan per pengguna
CREATE TABLE public.leave_balances (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  year INT NOT NULL,
  total_days INT NOT NULL DEFAULT 12,
  used_days INT NOT NULL DEFAULT 0,
  UNIQUE(user_id, year)
);

-- Tabel untuk notifikasi admin
CREATE TABLE public.notifications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  leave_request_id BIGINT NOT NULL REFERENCES public.leave_requests(id) ON DELETE CASCADE,
  message TEXT NOT NULL,
  is_read BOOLEAN DEFAULT FALSE NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW() NOT NULL
);


-- 3. Definisikan Fungsi Helper Penting
-- Fungsi untuk mendapatkan peran pengguna saat ini, digunakan di RLS.
CREATE OR REPLACE FUNCTION public.get_user_role()
RETURNS TEXT
LANGUAGE plpgsql
AS $$
BEGIN
  IF auth.uid() IS NULL THEN
    RETURN 'anon';
  ELSE
    RETURN (SELECT role FROM public.profiles WHERE id = auth.uid());
  END IF;
END;
$$;

-- Fungsi untuk membuat profil baru saat pengguna baru mendaftar
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
BEGIN
  INSERT INTO public.profiles (id, name, id_pjlp, phone, email, updated_at)
  VALUES (
    NEW.id,
    NEW.raw_user_meta_data->>'name',
    NEW.raw_user_meta_data->>'id_pjlp',
    NEW.raw_user_meta_data->>'phone',
    NEW.email,
    NOW()
  );
  RETURN NEW;
END;
$$;


-- 4. Setup Row Level Security (RLS)
-- PROFILES
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Users can view their own profile" ON public.profiles FOR SELECT USING (auth.uid() = id);
CREATE POLICY "Users can update their own profile" ON public.profiles FOR UPDATE USING (auth.uid() = id);
CREATE POLICY "Admins can manage all profiles" ON public.profiles FOR ALL USING ((SELECT get_user_role()) = 'admin');

-- LEAVE_REQUESTS
ALTER TABLE public.leave_requests ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Users can view their own leave requests" ON public.leave_requests FOR SELECT USING (auth.uid() = user_id);
CREATE POLICY "Users can create their own leave requests" ON public.leave_requests FOR INSERT WITH CHECK (auth.uid() = user_id);
CREATE POLICY "Users can update their own unread notifications" ON public.leave_requests FOR UPDATE USING (auth.uid() = user_id) WITH CHECK (auth.uid() = user_id);
CREATE POLICY "Admins can manage all leave requests" ON public.leave_requests FOR ALL USING ((SELECT get_user_role()) = 'admin');

-- LEAVE_BALANCES
ALTER TABLE public.leave_balances ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Users can view their own leave balances" ON public.leave_balances FOR SELECT USING (auth.uid() = user_id);
CREATE POLICY "Admins can manage all leave balances" ON public.leave_balances FOR ALL USING ((SELECT get_user_role()) = 'admin');

-- NOTIFICATIONS
ALTER TABLE public.notifications ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Admins can see their own notifications" ON public.notifications FOR SELECT USING (auth.uid() = user_id AND (SELECT get_user_role()) = 'admin');
CREATE POLICY "Admins can update their own notifications" ON public.notifications FOR UPDATE USING (auth.uid() = user_id AND (SELECT get_user_role()) = 'admin');


-- 5. Buat Fungsi untuk Triggers
-- Fungsi untuk membuat notifikasi untuk semua admin saat ada cuti baru.
CREATE OR REPLACE FUNCTION public.create_admin_notification_for_new_leave()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  admin_record RECORD;
  applicant_name TEXT;
BEGIN
  SELECT name INTO applicant_name FROM public.profiles WHERE id = NEW.user_id;
  IF applicant_name IS NULL THEN
    applicant_name := 'Seorang anggota';
  END IF;

  FOR admin_record IN SELECT id FROM public.profiles WHERE role = 'admin' LOOP
    INSERT INTO public.notifications (user_id, leave_request_id, message)
    VALUES (admin_record.id, NEW.id, applicant_name || ' mengajukan cuti baru: "' || NEW.title || '"');
  END LOOP;
  RETURN NEW;
END;
$$;

-- Fungsi untuk memperbarui saldo cuti saat status pengajuan diubah.
CREATE OR REPLACE FUNCTION public.handle_leave_balance_update()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  leave_year INT;
  default_total_days INT := 12;
BEGIN
  leave_year := EXTRACT(YEAR FROM NEW.start_date);

  -- Pastikan data saldo cuti ada, jika tidak, buat baru.
  INSERT INTO public.leave_balances (user_id, year, total_days, used_days)
  VALUES (NEW.user_id, leave_year, default_total_days, 0)
  ON CONFLICT (user_id, year) DO NOTHING;

  -- Jika status diubah menjadi 'Disetujui' dari status lain.
  IF NEW.status = 'Disetujui' AND OLD.status != 'Disetujui' THEN
    UPDATE public.leave_balances SET used_days = used_days + NEW.duration
    WHERE user_id = NEW.user_id AND year = leave_year;
  -- Jika persetujuan dibatalkan (dari 'Disetujui' menjadi status lain).
  ELSIF OLD.status = 'Disetujui' AND NEW.status != 'Disetujui' THEN
    UPDATE public.leave_balances SET used_days = used_days - NEW.duration
    WHERE user_id = NEW.user_id AND year = leave_year;
  END IF;

  RETURN NEW;
END;
$$;


-- 6. Setup Triggers
-- Trigger untuk handle_new_user
CREATE TRIGGER on_auth_user_created
AFTER INSERT ON auth.users
FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

-- Trigger untuk membuat notifikasi admin
CREATE TRIGGER on_new_leave_request_insert
AFTER INSERT ON public.leave_requests
FOR EACH ROW EXECUTE FUNCTION public.create_admin_notification_for_new_leave();

-- Trigger untuk update saldo cuti
CREATE TRIGGER on_leave_request_status_change
AFTER UPDATE ON public.leave_requests
FOR EACH ROW
WHEN (OLD.status IS DISTINCT FROM NEW.status)
EXECUTE FUNCTION public.handle_leave_balance_update();


-- 7. Setup Storage
-- Atur kebijakan untuk bucket 'attachments'
INSERT INTO storage.buckets (id, name, public)
VALUES ('attachments', 'attachments', FALSE)
ON CONFLICT (id) DO NOTHING;

CREATE POLICY "Users can upload attachments" ON storage.objects FOR INSERT
WITH CHECK (bucket_id = 'attachments' AND auth.uid() = (storage.foldername(name))[1]::uuid);

CREATE POLICY "Users can view their own attachments" ON storage.objects FOR SELECT
USING (bucket_id = 'attachments' AND auth.uid() = (storage.foldername(name))[1]::uuid);

CREATE POLICY "Admins can view all attachments" ON storage.objects FOR SELECT
USING (bucket_id = 'attachments' AND (SELECT get_user_role()) = 'admin');

