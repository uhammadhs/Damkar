-- Fungsi RPC untuk login menggunakan ID PJLP, menggabungkan beberapa query menjadi satu.
CREATE OR REPLACE FUNCTION public.login_with_id_pjlp(p_id_pjlp text, p_password text)
RETURNS json
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    v_email text;
    v_user_id uuid;
    v_role text;
    v_login_result json;
BEGIN
    -- 1. Cari email dan role berdasarkan ID PJLP
    SELECT email, id, role INTO v_email, v_user_id, v_role
    FROM public.profiles
    WHERE id_pjlp = p_id_pjlp;

    -- 2. Jika ID PJLP tidak ditemukan
    IF v_email IS NULL THEN
        RETURN json_build_object('error', 'ID PJLP tidak ditemukan.');
    END IF;

    -- 3. Coba untuk login menggunakan fungsi bawaan Supabase
    -- Ini akan memverifikasi password dan membuat sesi jika berhasil.
    SELECT sign_in INTO v_login_result FROM auth.sign_in(v_email, p_password);

    -- 4. Cek hasil login
    IF v_login_result->>'error' IS NOT NULL THEN
        -- Jika ada error dari auth.sign_in (misal: password salah)
        RETURN json_build_object('error', 'Password yang Anda masukkan salah.');
    END IF;
    
    -- 5. Jika login berhasil, kembalikan data yang dibutuhkan aplikasi
    RETURN json_build_object(
        'success', true,
        'user_id', v_user_id,
        'role', v_role,
        'email', v_email
    );
EXCEPTION
    -- Menangani kesalahan tak terduga
    WHEN others THEN
        RETURN json_build_object('error', 'Terjadi kesalahan internal yang tidak diketahui saat login.');
END;
$$;


-- =============================================
-- 4. KEBIJAKAN KEAMANAN (ROW LEVEL SECURITY)
-- =============================================

-- Kebijakan untuk tabel profiles
CREATE POLICY "Users can view their own profile." ON public.profiles FOR SELECT USING (auth.uid() = id);
CREATE POLICY "Users can update their own profile." ON public.profiles FOR UPDATE USING (auth.uid() = id);
CREATE POLICY "Admins can view all profiles." ON public.profiles FOR SELECT TO authenticated USING (get_user_role() = 'admin');
CREATE POLICY "Admins can manage all profiles." ON public.profiles FOR ALL TO authenticated USING (get_user_role() = 'admin') WITH CHECK (get_user_role() = 'admin');

-- Kebijakan untuk tabel leave_requests
CREATE POLICY "Users can manage their own leave requests." ON public.leave_requests FOR ALL USING (auth.uid() = user_id);
CREATE POLICY "Admins can view all leave requests." ON public.leave_requests FOR SELECT TO authenticated USING (get_user_role() = 'admin');
CREATE POLICY "Admins can update leave requests." ON public.leave_requests FOR UPDATE TO authenticated USING (get_user_role() = 'admin') WITH CHECK (get_user_role() = 'admin');

-- Kebijakan untuk tabel leave_balances
CREATE POLICY "Users can view their own leave balance." ON public.leave_balances FOR SELECT USING (auth.uid() = user_id);
CREATE POLICY "Admins can view all leave balances." ON public.leave_balances FOR SELECT TO authenticated USING (get_user_role() = 'admin');
CREATE POLICY "Admins can update all leave balances." ON public.leave_balances FOR UPDATE TO authenticated USING (get_user_role() = 'admin') WITH CHECK (get_user_role() = 'admin');

-- Kebijakan untuk tabel notifications
CREATE POLICY "Admins can manage their own notifications." ON public.notifications FOR ALL TO authenticated USING (auth.uid() = user_id AND get_user_role() = 'admin');


-- =============================================
-- 5. PEMICU (TRIGGERS)
-- =============================================

-- Pemicu untuk menjalankan `handle_new_user` setiap kali pengguna baru mendaftar di Supabase Auth.
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE PROCEDURE public.handle_new_user();

-- Pemicu untuk menjalankan `create_admin_notification_for_new_leave` setiap kali ada pengajuan cuti baru.
CREATE TRIGGER on_leave_request_created
  AFTER INSERT ON public.leave_requests
  FOR EACH ROW EXECUTE PROCEDURE public.create_admin_notification_for_new_leave();

