-- Kunci utama dan batasan
alter table "public"."leave_balances" enable row level security;
create index leave_balances_user_id_year_idx on public.leave_balances using btree (user_id, year);
create sequence "public"."leave_balances_id_seq" as integer start with 1 increment by 1 no minvalue no maxvalue cache 1;
alter sequence "public"."leave_balances_id_seq" owned by "public"."leave_balances"."id";
alter table "public"."leave_balances" add constraint "leave_balances_pkey" primary key (id);
alter table "public"."leave_balances" add constraint "leave_balances_user_id_fkey" foreign key (user_id) references public.profiles(id) on delete cascade;
alter table "public"."leave_balances" add constraint leave_balances_user_id_year_key unique (user_id, year);

