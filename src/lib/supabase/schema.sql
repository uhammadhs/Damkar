-- =============================================
-- 3. PEMBUATAN FUNGSI
-- =============================================

-- Fungsi untuk mendapatkan peran (role) dari pengguna yang sedang login.
CREATE OR REPLACE FUNCTION public.get_user_role()
RETURNS text
LANGUAGE sql
SECURITY DEFINER
SET search_path = public
AS $$
    SELECT role FROM public.profiles WHERE id = auth.uid();
$$;

-- Fungsi untuk membuat profil dan saldo cuti awal saat pengguna baru mendaftar.
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
  current_year integer := date_part('year', now());
BEGIN
  -- Membuat profil baru
  INSERT INTO public.profiles (id, name, id_pjlp, phone, email, role)
  VALUES (
    new.id,
    new.raw_user_meta_data->>'name',
    new.raw_user_meta_data->>'id_pjlp',
    new.raw_user_meta_data->>'phone',
    new.email,
    'anggota' -- Default role
  );

  -- Membuat saldo cuti awal untuk tahun berjalan
  INSERT INTO public.leave_balances (user_id, year, total_days, used_days)
  VALUES (new.id, current_year, 12, 0);

  RETURN new;
END;
$$;

-- Fungsi untuk membuat notifikasi ke semua admin saat ada pengajuan cuti baru.
CREATE OR REPLACE FUNCTION public.create_admin_notification_for_new_leave()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  admin_record record;
  notification_message text;
BEGIN
  -- Pesan notifikasi
  notification_message := (SELECT name FROM public.profiles WHERE id = NEW.user_id) || ' telah mengajukan cuti baru.';

  -- Loop melalui semua admin dan buat notifikasi untuk mereka
  FOR admin_record IN SELECT id FROM public.profiles WHERE role = 'admin' LOOP
    INSERT INTO public.notifications (user_id, leave_request_id, message)
    VALUES (admin_record.id, NEW.id, notification_message);
  END LOOP;

  RETURN NEW;
END;
$$;

-- Fungsi untuk mereset saldo cuti semua anggota di awal tahun.
CREATE OR REPLACE FUNCTION public.handle_new_year_leave_balances()
RETURNS void
LANGUAGE plpgsql
AS $$
DECLARE
    user_record RECORD;
    current_year INTEGER := EXTRACT(YEAR FROM NOW());
BEGIN
    FOR user_record IN SELECT id FROM public.profiles WHERE role = 'anggota' LOOP
        -- Hanya insert jika data untuk tahun baru belum ada, untuk menghindari duplikasi
        INSERT INTO public.leave_balances (user_id, year, total_days, used_days)
        VALUES (user_record.id, current_year, 12, 0)
        ON CONFLICT (user_id, year) DO NOTHING;
    END LOOP;
END;
$$;

