
-- 1. Hapus tabel-tabel lama jika ada (untuk pengembangan ulang)
drop table if exists "public"."leave_balances" cascade;
drop table if exists "public"."leave_requests" cascade;
drop table if exists "public"."notifications" cascade;
drop table if exists "public"."profiles" cascade;

-- 2. Buat Tabel PROFILES
-- Menyimpan data publik untuk setiap pengguna.
create table "public"."profiles" (
    "id" uuid not null,
    "updated_at" timestamp with time zone,
    "name" text,
    "avatar_url" text,
    "role" text default 'anggota'::text,
    "id_pjlp" text,
    "phone" text,
    "email" text
);
-- Kunci utama dan batasan
alter table "public"."profiles" enable row level security;
create unique index profiles_id_pjlp_key on public.profiles using btree (id_pjlp);
create unique index profiles_pkey on public.profiles using btree (id);
alter table "public"."profiles" add constraint "profiles_pkey" primary key using index "profiles_pkey";
alter table "public"."profiles" add constraint "profiles_id_fkey" foreign key (id) references auth.users(id) on delete cascade;
alter table "public"."profiles" add constraint "profiles_id_pjlp_key" unique using index "profiles_id_pjlp_key";
-- Komentar pada kolom
comment on column "public"."profiles"."role" is 'User role (e.g., ''admin'', ''anggota'')';
comment on column "public"."profiles"."id_pjlp" is 'Unique ID for PJLP';

-- 3. Buat Tabel LEAVE_REQUESTS
-- Menyimpan semua data pengajuan cuti dari pengguna.
create table "public"."leave_requests" (
    "id" bigint generated by default as identity not null,
    "created_at" timestamp with time zone not null default now(),
    "title" text not null,
    "reason" text,
    "start_date" date not null,
    "end_date" date not null,
    "status" text not null default 'Menunggu'::text,
    "user_id" uuid not null,
    "attachment_url" text,
    "updated_at" timestamp with time zone not null default now(),
    "duration" integer not null,
    "is_read_by_user" boolean not null default false
);
-- Kunci utama dan batasan
alter table "public"."leave_requests" enable row level security;
create index leave_requests_user_id_status_idx on public.leave_requests using btree (user_id, status);
create index leave_requests_status_idx on public.leave_requests using btree (status);
create index leave_requests_user_id_idx on public.leave_requests using btree (user_id);
create sequence "public"."leave_requests_id_seq" as integer start with 1 increment by 1 no minvalue no maxvalue cache 1;
alter sequence "public"."leave_requests_id_seq" owned by "public"."leave_requests"."id";
alter table "public"."leave_requests" add constraint "leave_requests_pkey" primary key (id);
alter table "public"."leave_requests" add constraint "leave_requests_user_id_fkey" foreign key (user_id) references public.profiles(id) on delete cascade;
alter table "public"."leave_requests" add constraint leave_requests_duration_check check ((duration > 0));

-- 4. Buat Tabel LEAVE_BALANCES
-- Menyimpan saldo cuti tahunan setiap pengguna.
create table "public"."leave_balances" (
    "id" bigint generated by default as identity not null,
