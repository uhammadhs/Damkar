-- Kebijakan untuk tabel 'profiles'
CREATE POLICY "Public profiles are viewable by everyone." ON public.profiles FOR SELECT USING (true);
CREATE POLICY "Users can insert their own profile." ON public.profiles FOR INSERT WITH CHECK (auth.uid() = id);
CREATE POLICY "Users can update their own profile." ON public.profiles FOR UPDATE USING (auth.uid() = id);
CREATE POLICY "Admins can manage all profiles." ON public.profiles FOR ALL USING (get_user_role() = 'admin');

-- Kebijakan untuk tabel 'leave_requests'
CREATE POLICY "Members can CRUD their own leave requests" ON public.leave_requests
    FOR ALL
    USING (auth.uid() = user_id)
    WITH CHECK (auth.uid() = user_id);
CREATE POLICY "Admin can manage all leave requests" ON public.leave_requests
    FOR ALL
    USING (get_user_role() = 'admin');

-- Kebijakan untuk tabel 'leave_balances'
CREATE POLICY "Members can view their own leave balance" ON public.leave_balances
    FOR SELECT
    USING (auth.uid() = user_id);
CREATE POLICY "Admin can view all leave balances" ON public.leave_balances
    FOR SELECT
    USING (get_user_role() = 'admin');

-- Kebijakan untuk tabel 'notifications'
CREATE POLICY "Admin can see all notifications" ON public.notifications
    FOR SELECT
    USING (get_user_role() = 'admin' AND auth.uid() = user_id);
CREATE POLICY "Admin can update their own read status" ON public.notifications
    FOR UPDATE
    USING (get_user_role() = 'admin' AND auth.uid() = user_id);

